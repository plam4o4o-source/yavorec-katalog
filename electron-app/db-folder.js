'use strict';
/* Проверка дали настроената папка с базата данни е достъпна, преди тя да бъде отворена.
 *
 * Защо съществува този модул: resolveDbDir() в main.js досега се връщаше ТИХО към
 * локалната папка по подразбиране, ако настроената (обичайно мрежов диск, споделен
 * между работните места) не съществува. resolveDbPath() след това правеше mkdir и
 * better-sqlite3 създаваше на място НОВА, ПРАЗНА база. От гледна точка на библиотекаря
 * това изглежда като пълна загуба на данни — фондът, читателите и заеманията ги няма.
 * По-опасното идва след това: ако човекът приеме, че „днес просто е празно“, и започне
 * да въвежда, тези записи остават в локалната база и никога не се срещат с общата.
 *
 * Затова тук се пита изрично. Логиката е отделена от Electron (диалогът се подава
 * отвън като функция `ask`), за да може да се тества без работещо приложение.
 */

/** 'ok' = може да се продължи; 'missing' = настроена е папка, но я няма. */
function dbFolderDecision(cfg, existsSync) {
  if (!cfg || !cfg.dbFolder) return 'ok'; // няма настроена папка — важи локалната по подразбиране
  return existsSync(cfg.dbFolder) ? 'ok' : 'missing';
}

/* Връща true, ако програмата може да продължи (папката е налична или потребителят
 * съзнателно е избрал локална база), и false, ако е избрал „Изход“.
 *
 * `ask(folder)` трябва да върне 'retry' | 'local' | 'quit'. Повторните опити са
 * ограничени, за да не може повреден диалог да завърти безкраен цикъл.
 */
function ensureDbFolderAvailable({ readConfig, existsSync, ask, maxAttempts = 50 }) {
  for (let i = 0; i < maxAttempts; i++) {
    const cfg = readConfig();
    if (dbFolderDecision(cfg, existsSync) === 'ok') return true;
    const answer = ask(cfg.dbFolder);
    if (answer === 'local') return true;
    if (answer === 'quit') return false;
    // 'retry' — нов кръг: конфигурацията и дискът се четат отново
  }
  return false; // изчерпани опити — по-безопасно е да не се създава празна база
}

module.exports = { dbFolderDecision, ensureDbFolderAvailable };
