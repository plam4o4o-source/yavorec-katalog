// Малки, чисти помощни функции за сигурност — извадени в отделен non-Electron
// модул (както backup-crypto.js/pii-crypto.js/search-fts.js/debounce.js), за
// да са тестваеми с node:test без main.js. Фаза 3 от плана (Electron/security
// hardening): CSV formula-injection защита и валидация на mailto адрес.

// Защита срещу CSV/formula injection (OWASP): ако клетка започва с '=', '+',
// '-', '@' или таб/CR, Excel/LibreOffice могат да я изпълнят като формула (или
// дори системна команда) при отваряне на файла — напр. заглавие на книга
// "=cmd|'/c calc'!A1", въведено случайно или нарочно от каталогизатора. Водещ
// апостроф преди опасния символ неутрализира изпълнението, без видимо да
// променя показаната стойност в повечето програми за таблици.
function csvCell(x) {
  let s = String(x ?? '');
  if (/^[=+\-@\t\r]/.test(s)) s = "'" + s;
  return '"' + s.replace(/"/g, '""') + '"';
}

// Одит v2.3.1 №6: handlers/loans.js приемаше дата на връщане (date_due) без
// никаква проверка — '0000-00-00', '2026-13-45' и 'not-a-date' минаваха
// тихо, а '2026-02-30' JS я търкулваше напред до 2 март БЕЗ грешка. По-късно
// effectiveDaysLate() върху невалидна дата дава NaN, което по IPC пристига
// като null — екранът "Просрочени" показва празни/безсмислени дни закъснение
// и глоба, без никаква следа защо. Проверката тук е нарочно СТРОГА (не просто
// регулярен израз): "2026-02-30" минава regex-а, но е невалидна дата, затова
// след regex-а датата се пресъздава през Date.UTC и се сравнява обратно —
// само истинско превъртане (30 февруари -> 2 март) проваля тази проверка.
const ISO_DATE_RE = /^(\d{4})-(\d{2})-(\d{2})$/;
function isValidIsoDate(s) {
  const m = ISO_DATE_RE.exec(String(s == null ? '' : s));
  if (!m) return false;
  const y = Number(m[1]), mo = Number(m[2]), d = Number(m[3]);
  if (mo < 1 || mo > 12 || d < 1 || d > 31) return false;
  const dt = new Date(Date.UTC(y, mo - 1, d));
  return dt.getUTCFullYear() === y && dt.getUTCMonth() === mo - 1 && dt.getUTCDate() === d;
}

// Груба, но достатъчна проверка на формата на имейл — не техническа коректност
// на самия адрес е целта (mailto: схемата и без това е фиксирана буквално в
// main.js, не идва от полето), а да не подадем съвсем несвързан низ от
// читателската картотека към shell.openExternal.
const EMAIL_RE = /^[^\s@"]+@[^\s@]+\.[^\s@]+$/;
function isValidEmail(email) {
  return EMAIL_RE.test(String(email == null ? '' : email).trim());
}

// Кирилски буквени клавиши от стандартната Windows разредба „Български
// (фонетичен)“ → латинската буква на СЪЩИЯ физически клавиш (v1.70.1).
// Баркод четците се държат като физическа клавиатура и изпращат кода буква по
// буква, без да знаят коя разредба е активна в момента в Windows. Баркодовете
// тук са Code 39 (виж code39svg() в src/views/core.js) — азбуката му е само
// 0-9, A-Z и няколко символа, НИКОГА кирилица — затова щом библиотеката е
// активна с фонетичната кирилска разредба, "B00108" от четеца пристига като
// "Б00108" в полето: същият клавиш B, но операционната система го превежда
// през активната разредба, не през тази, за която е калибриран четецът.
// Открито на живо: читателска карта с код „B00108“ не се намираше при
// сканиране, защото стигаше до readers:byCard като „Б00108“.
const CYR_TO_LAT_SCAN = {
  'Я': 'Q', 'В': 'W', 'Е': 'E', 'Р': 'R', 'Т': 'T', 'Ъ': 'Y', 'У': 'U', 'И': 'I', 'О': 'O', 'П': 'P',
  'А': 'A', 'С': 'S', 'Д': 'D', 'Ф': 'F', 'Г': 'G', 'Х': 'H', 'Й': 'J', 'К': 'K', 'Л': 'L',
  'З': 'Z', 'Ь': 'X', 'Ц': 'C', 'Ж': 'V', 'Б': 'B', 'Н': 'N', 'М': 'M'
};
// Малки кирилски букви — за да не се чупи баркод, сканиран докато Caps Lock е
// изключен (Windows превежда клавиша, не регистъра сам по себе си).
const CYR_TO_LAT_SCAN_LOWER = Object.fromEntries(
  Object.entries(CYR_TO_LAT_SCAN).map(([cy, la]) => [cy.toLowerCase(), la.toLowerCase()])
);
// Одит v2.3.1 №23: баркод четецът понякога праща и вътрешни контролни знаци
// (напр. таб/нов ред от бъгав драйвер, или сканиране, прекъснато по средата) —
// те не се виждат в интерфейса, но остават в стойността и правят "12\n34" ≠
// "1234" при сравнение с базата, вместо ясно съобщение "не е намерен".
// Премахват се ВСИЧКИ контролни знаци (\x00-\x1F, \x7F), не само водещи/
// опашни whitespace знаци (тях trim() вече маха).
// Второ: код, съставен САМО от whitespace/контролни знаци, преди се
// нормализираше до '' — а всеки повикващ пита базата с
// "... OR inv_number = CAST(? AS INTEGER)", където CAST('' AS INTEGER) = 0 в
// SQLite. Ако в базата случайно има ред с inv_number = 0 (стар внос/ръчна
// поправка), празно сканиране мълчаливо намираше ИМЕННО него. Връщането на
// `null` вместо '' затваря дупката за всички повикващи наведнъж: SQL
// сравнение с NULL никога не е истина (нито за barcode = NULL, нито за
// inv_number = CAST(NULL AS INTEGER)), а всеки повикващ вече проверява
// `if (!b) throw ...` — точно поведението за "не е намерен".
function normalizeScanCode(code) {
  let s = String(code == null ? '' : code).replace(/[\x00-\x1F\x7F]/g, '').trim();
  if (!s) return null;
  s = s.replace(/[А-Яа-я]/g, ch => CYR_TO_LAT_SCAN[ch] || CYR_TO_LAT_SCAN_LOWER[ch] || ch);
  return s;
}

/* Служебният запис, под който handlers/gdpr.js прибира анонимизираните заемания.
   Живее тук, защото го ползват четири модула (gdpr, stats, dashboard и тестовете)
   и защото разминаване между тях е точно дефектът, който одит v2.4.14 намери:
   dashboard.js вече го изключваше поименно при пререгистрациите, а годишните
   броячи на читатели — не, и двете числа за читатели в един и същи годишен отчет
   се разминаваха с единица. */
const ANON_READER_NAME = '— анонимизирани заемания —';

/* Пореден номер на документ в регистър (партида, акт, протокол, заявка за МЗС).
   Дотук навсякъде стоеше `parseInt(x, 10)`: „1.5“ ставаше 1, „1e3“ (валидно в
   <input type=number>) ставаше 1, „-3“ се записваше като „№ -3“, а „0“ в
   протокола по чл. 40 пропадаше през `typed || MAX+1` и мълчаливо ставаше
   следващият номер (одит v2.4.21). Номерът е цяло положително число — или
   грешка, която казва защо. `allowEmpty` е за регистрите, които сами предлагат
   следващия номер при празно поле. */
function parseRegisterNo(x, label, allowEmpty) {
  const raw = x === undefined || x === null ? '' : String(x).trim();
  if (raw === '') {
    if (allowEmpty) return null;
    throw new Error((label || 'Номерът') + ' е задължителен.');
  }
  if (!/^\d{1,9}$/.test(raw) || Number(raw) < 1) {
    throw new Error((label || 'Номерът') + ' трябва да е цяло положително число (въведено: „' + raw + '“).');
  }
  return Number(raw);
}
/* Разчита сканиран/въведен код до ЕДИН документ.
   Дотук на пет места стоеше `WHERE barcode = ? OR inv_number = CAST(? AS INTEGER)`
   с `.get()`. Числов баркод се преобразува и към инвентарен номер, тоест един
   скан можеше да съвпадне И с баркода на един документ, И с инвентарния номер на
   ДРУГ — а SQLite връща реда с по-малкия rowid, обикновено съвпадението по
   инвентарен номер. Проверено (одит v2.4.24): „Под игото“ инв. № 123 без баркод и
   „Тютюн“ инв. № 500 с етикет 0000123 — сканирането на етикета на „Тютюн“ заемаше
   „Под игото“, а по-късно същият скан затваряше чуждото заемане.
   Баркодът е физически залепен на конкретния екземпляр и е по-силният признак,
   затова се търси ПЪРВО той. Истинска двусмислица (баркодът сочи един документ,
   номерът — друг, или един баркод стои на няколко документа) не се решава с
   догадка: това е данни за поправяне и се казва на библиотекаря, вместо да се
   завери, заеме или отчисли грешният физически екземпляр. */
function resolveScannedBook(db, code, select) {
  const c = String(code == null ? '' : code).trim();
  if (!c) throw new Error('Не е въведен баркод или инвентарен номер.');
  const sel = select || 'SELECT * FROM books';
  const byBarcode = db.prepare(`${sel} WHERE barcode = ? ORDER BY id`).all(c);
  const byInv = /^\d{1,9}$/.test(c)
    ? db.prepare(`${sel} WHERE inv_number = CAST(? AS INTEGER) ORDER BY id`).all(c)
    : [];
  const name = (b) => 'инв. № ' + (b.inv_number == null ? '—' : b.inv_number) + (b.title ? ' — ' + b.title : '');
  if (byBarcode.length > 1) {
    throw new Error('Баркод „' + c + '“ стои на ' + byBarcode.length + ' документа (' +
      byBarcode.map(name).join('; ') + '). Сканирането не може да познае кой е пред вас. ' +
      'Поправете дубликата от „Настройки“ → „Проверка на данните“.');
  }
  if (byBarcode.length === 1) {
    const other = byInv.find(b => b.id !== byBarcode[0].id);
    if (other) {
      throw new Error('Кодът „' + c + '“ е баркод на ' + name(byBarcode[0]) + ', но е и инвентарен номер на ' +
        name(other) + '. Въведете кода на другия документ или поправете етикета — програмата няма да гадае ' +
        'кой физически екземпляр държите.');
    }
    return byBarcode[0];
  }
  if (byInv.length > 1) {
    // inv_number е UNIQUE в схемата — до тук се стига само при ръчно пипана база.
    throw new Error('Инвентарен номер ' + c + ' стои на ' + byInv.length + ' документа. Поправете базата.');
  }
  return byInv[0] || null;
}
