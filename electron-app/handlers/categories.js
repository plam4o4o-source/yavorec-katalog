// Категории (на книгите) — извадени от main.js в отделен модул (Фаза 4,
// стъпка 7 от разбиването на монолита на модули по домейн). Най-простият
// случай досега: 4 реда логика, само `getDb()`/`run`, без `logAudit`, без
// нито една върната функция назад — други места в main.js (внос, справки)
// продължават да четат таблицата `categories` директно през собствения си
// `db`, без да минават през този модул, и това е ОК — той не пази никакво
// състояние, само регистрира IPC handler-и.
module.exports = function registerCategoriesHandlers(ipcMain, deps) {
  const { getDb, run, logAudit } = deps;

  ipcMain.handle('categories:list', () =>
    run(() => getDb().prepare('SELECT * FROM categories ORDER BY name').all())
  );
  ipcMain.handle('categories:create', (e, name) =>
    run(() => getDb().prepare('INSERT INTO categories (name) VALUES (?)').run(name.trim()))
  );
  /* Със следа (одит v2.4.25): преименуването преетикетира „Вид документ“ на всяка
     книга в инвентарната книга (Приложение № 4), а изтриването е в следата от
     v2.4.14 — преименуването трябва да е също. */
  /* НАЧАЛНИТЕ ВИДОВЕ ИМАТ КОД И ПРЕИМЕНУВАНЕТО ИМ СЕ ОТБЕЛЯЗВА (одит v2.4.61, находка 19).
     =====================================================================
     ДОТУК преименуването беше просто UPDATE: етикетът е на библиотекаря и това е
     вярно — Наредба № 3 не предписва имената на видовете. Само че ДВЕ места в
     програмата разпознаваха вида по буквалното му име: Дневникът (Раздел Б,
     редът „Периодични издания“) и инвентирането на годишен комплект. Едно
     преименуване на „продължаващо издание“ значеше заетият вестник да се брои в
     „Книги“, а следващото инвентиране да СЪЗДАДЕ втора категория със старото име
     — и фондът да излезе с два вида за една и съща периодика в КДБФ и в годишния
     отчет.
     Поправено е в корена: началните видове носят непроменлив `code`
     (db/schema.sql + миграция 16), и програмата гледа кода, не името. Тоест
     преименуването вече е БЕЗОПАСНО и затова остава позволено — библиотека,
     която води „периодични издания“, има право да го пише така на своите
     разпечатки.
     Тук остава единственото, което все пак трябва да се знае: че е преименуван
     вид, който програмата ползва вътрешно, и че старото име е отпечатано по
     документи (инвентарна книга, актове, КДБФ) от преди. Това влиза в следата. */
  const codeOf = (db, id) => {
    const hasCode = db.prepare("SELECT COUNT(*) AS n FROM pragma_table_info('categories') WHERE name = 'code'").get().n > 0;
    if (!hasCode) return null;
    const row = db.prepare('SELECT code FROM categories WHERE id = ?').get(id);
    return row ? row.code : null;
  };
  ipcMain.handle('categories:update', (e, { id, name }) =>
    run(() => {
      const db = getDb();
      const cur = db.prepare('SELECT name FROM categories WHERE id = ?').get(id);
      if (!cur) throw new Error('Видът документ не е намерен.');
      const next = String(name || '').trim();
      if (!next) throw new Error('Името не може да е празно.');
      const code = codeOf(db, id);
      db.prepare('UPDATE categories SET name = ? WHERE id = ?').run(next, id);
      if (next !== cur.name) {
        const n = db.prepare('SELECT COUNT(*) AS n FROM books WHERE category_id = ?').get(id).n;
        logAudit('Преименуван вид документ', '„' + cur.name + '“ → „' + next + '“'
          + (n ? ' (' + n + (n === 1 ? ' документ' : ' документа') + ')' : '')
          + (code ? ' — това е един от началните видове (вътрешен код „' + code + '“); програмата го намира по '
            + 'кода, не по име, но вече отпечатаните документи остават със старото название' : ''));
      }
    })
  );
  /* books.category_id е обявена като ON DELETE SET NULL (db/schema.sql) и
     PRAGMA foreign_keys е включена, тоест изтриването на категория изчиства вида
     на документа на ВСЯКА книга, която я е ползвала — необратимо и без следа.
     Одит v2.4.14: питането на екрана казваше само „Да изтрия ли тази категория?“,
     а модулът беше регистриран без logAudit, тоест в одитната следа не оставаше
     нищо. Броят засегнати книги се връща предварително (categories:usage), за да
     влезе в питането, а самото изтриване вече се вписва. */
  ipcMain.handle('categories:usage', (e, id) =>
    run(() => getDb().prepare('SELECT COUNT(*) AS n FROM books WHERE category_id = ?').get(id).n)
  );
  ipcMain.handle('categories:delete', (e, id) =>
    run(() => {
      const db = getDb();
      const c = db.prepare('SELECT name FROM categories WHERE id = ?').get(id);
      const n = db.prepare('SELECT COUNT(*) AS n FROM books WHERE category_id = ?').get(id).n;
      /* ЗАЕТ НАЧАЛЕН ВИД НЕ СЕ ТРИЕ (одит v2.4.61, находка 19).
         books.category_id е ON DELETE SET NULL, тоест изтриването изчиства вида
         на всеки документ, който го ползва — необратимо. Дотук това се допускаше
         за всяка категория и се вписваше само в следата. За вид от началните
         (онзи, който носи `code`) обаче цената е по-висока от загубения етикет:
         по вида се строят КДБФ Приложение № 2 („по видове документи“), редът на
         Дневника, Раздел Б, и разбивката в годишния отчет. Документи без вид
         изпадат от всички тях наведнъж и се връщат обратно само на ръка, документ
         по документ.
         Затова: начален вид с документи зад себе си се отказва (с указание какво
         да се направи вместо това), а празен начален вид може да бъде изтрит —
         той не държи нищо, а инвентирането на периодика умее да си го създаде
         наново, ако потрябва. Вид, създаден от библиотекаря, не се пипа. */
      const hasCode = db.prepare("SELECT COUNT(*) AS n FROM pragma_table_info('categories') WHERE name = 'code'").get().n > 0;
      const code = hasCode ? (db.prepare('SELECT code FROM categories WHERE id = ?').get(id) || {}).code : null;
      if (code && n > 0) {
        throw new Error('Видът „' + (c ? c.name : id) + '“ е един от началните видове документи и по него '
          + (n === 1 ? 'е записан 1 документ' : 'са записани ' + n + ' документа') + '. Изтриването му би оставило '
          + (n === 1 ? 'този документ' : 'тези документи') + ' без вид — а по вида се строят КДБФ (Приложение № 2), '
          + 'редът на Дневника и годишният отчет. Ако името не ви върши работа, преименувайте го; ако документите '
          + 'са от друг вид, сменете вида им във „Фонд“ и чак тогава изтрийте този.');
      }
      db.prepare('DELETE FROM categories WHERE id = ?').run(id);
      logAudit('Категория', 'изтрита „' + (c ? c.name : id) + '“'
        + (n ? ' — ' + (n === 1 ? '1 документ остана' : n + ' документа останаха') + ' без вид' : ''));
      return n;
    })
  );
};
