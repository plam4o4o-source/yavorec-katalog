// Местоположение на базата данни — извадени от main.js в отделен модул
// (Фаза 4, стъпка 9 от разбиването на монолита на модули по домейн).
// Позволява библиотеката да ползва мрежова папка вместо локалната по
// подразбиране (споделена база между няколко работни компютъра).
//
// Същия DI модел като backup.js: `db`/`mainWindow` — getter/setter функции
// (`dbLocation:choose`/`resetDefault` затварят db и правят app.relaunch()+
// app.exit(0), точно като backup.js — процесът приключва веднага след
// записа в config.json, следващото стартиране прочита новата папка).
// `readConfig`/`writeConfig`/`resolveDbDir`/`resolveDbPath` се подават по
// референция — дефинирани са в main.js и остават там (ползва ги и
// initDb() при стартиране, извън обхвата на този модул).
module.exports = function registerDbLocationHandlers(ipcMain, deps) {
  const {
    app, dialog, fs, path,
    getDb, setDb, getMainWindow,
    run, readConfig, writeConfig, updateConfig, resolveDbDir, resolveDbPath
  } = deps;

  /* ==========================================================================
     ОДИТНА СЛЕДА ЗА ПРЕМЕСТВАНЕТО НА БАЗАТА (v2.4.65, кръг 42, находка Б21)
     ==========================================================================
     (а) КАКВО СТАВАШЕ ДОТУК. ЦЕЛИЯТ този модул минаваше без нито един ред в
     следата — включително „Ползвай съществуващата база от тази папка“, което е
     смяна на целия регистър на библиотеката с друг, и „Върни стандартната
     папка“, което я връща обратно. Резултатът: библиотекарка отваря програмата
     и вижда фонд, който не познава (или своя, но без последните две седмици),
     а нищо никъде не казва, че базата е била сменена, кога и с коя.
     (б) ЗАЩО Е ГРЕШНО. По чл. 17, ал. 2 от Наредба № 3 следата отговаря „кой,
     кога, какво“ за вписванията в регистрите. Смяната на САМИЯ регистър е
     по-голямо действие от всяко вписване в него и е единственото, което
     програмата извършваше безмълвно. Съседният модул (handlers/backup.js) вече
     вписва възстановяването от копие — същото действие по резултат.
     (в) ЗАЩО ТОЧНО ТАКА — И В КОЯ БАЗА. Ред, вписан само в текущата база, не
     стига доникъде, когато точно тя бъде изоставена: след рестарта програмата
     отваря ДРУГ файл. Затова редът се пише на двете страни:
       • в базата, която си отива — за да личи в нея (и в копията ѝ) кога и
         накъде е тръгнал компютърът;
       • в базата, която застава на нейно място — за да отвори следата ѝ с реда
         „от тази дата тази база се ползва от този компютър“.
     Когато базата се ПРЕНАСЯ (копира се върху новото място), редът се пише
     ПРЕДИ копирането и пътува с него — второ вписване не е нужно и не се прави.
     Провал на вписването НЕ отменя преместването: по-добре преместена база без
     ред, отколкото отказ заради невъзможно вписване (затова грешката се
     съобщава, а не се поглъща).
     `logAudit` НЕ е сред зависимостите, които main.js подава на този модул
     (main.js:1065–1069), а main.js е забранен за промяна в този кръг — затова
     редът се пише със същото изявление, с което го пише самият logAudit
     (main.js:1775–1778). Ако някой ден бъде подаден, се ползва той. */
  function lastUserIn(conn) {
    try {
      const last = conn.prepare("SELECT user FROM audit_log WHERE COALESCE(user, '') != '' ORDER BY id DESC LIMIT 1").get();
      return (last && last.user) || '';
    } catch (e) {
      return ''; // празна колона „кой“ е по-добра от липсващ ред
    }
  }
  function noteInLiveDb(action, detail) {
    try {
      if (typeof deps.logAudit === 'function') { deps.logAudit(action, detail); return; }
      const db = getDb();
      if (!db) return;
      db.prepare('INSERT INTO audit_log (user, action, detail, diff) VALUES (?, ?, ?, NULL)')
        .run(lastUserIn(db), action, detail);
    } catch (err) {
      console.error('Редът за смяната на папката не можа да се впише в текущата база:', err.message);
    }
  }
  /* Вписване в ДРУГ файл с база — онзи, който програмата ще отвори след
     рестарта. Отделна връзка, затворена веднага. */
  function noteInDbFile(dbFile, action, detail, who) {
    let conn = null;
    try {
      if (!fs.existsSync(dbFile)) return;
      const Database = require('better-sqlite3');
      conn = new Database(dbFile);
      const has = conn.prepare("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'audit_log'").get();
      if (!has) return; // база от толкова стара схема, че таблицата я няма
      conn.prepare('INSERT INTO audit_log (ts, user, action, detail, diff) VALUES (?, ?, ?, ?, NULL)').run(
        new Date().toISOString().slice(0, 19).replace('T', ' '),
        who || lastUserIn(conn), action, detail);
    } catch (err) {
      console.error('Редът за смяната на папката не можа да се впише в новата база:', err.message);
    } finally {
      if (conn) { try { conn.close(); } catch (e) { /* връзката и без това си отива */ } }
    }
  }

  ipcMain.handle('dbLocation:get', () =>
    run(() => ({ folder: resolveDbDir(), isDefault: !readConfig().dbFolder, isPackaged: app.isPackaged }))
  );
  ipcMain.handle('dbLocation:choose', async () => {
    try {
      const { canceled, filePaths } = await dialog.showOpenDialog(getMainWindow(), {
        title: 'Изберете папка за базата данни (локална или мрежова)',
        properties: ['openDirectory', 'createDirectory']
      });
      if (canceled || !filePaths[0]) return { ok: false, error: 'Отказано от потребителя.' };
      const newDir = filePaths[0];
      const oldPath = resolveDbPath();
      const newPath = path.join(newDir, 'library.db');
      if (path.resolve(oldPath) === path.resolve(newPath)) return { ok: false, error: 'Това е текущата папка на базата данни.' };

      // В избраната папка вече може да има library.db — най-често защото това е
      // споделена мрежова база, към която друг компютър в библиотеката вече е
      // свързан. Копирането по подразбиране тук би я презаписало безвъзвратно
      // с текущата (локална) база, затова питаме изрично какво иска потребителят.
      let doCopy = true;
      if (fs.existsSync(newPath)) {
        const { response } = await dialog.showMessageBox(getMainWindow(), {
          type: 'warning',
          buttons: ['Отказ', 'Ползвай съществуващата база от тази папка', 'Презапиши я с моята текуща база'],
          defaultId: 1,
          cancelId: 0,
          title: 'В папката вече има база данни',
          message: 'В избраната папка вече има файл library.db.',
          detail: 'Ако това е споделена мрежова база на библиотеката, изберете „Ползвай съществуващата база" — текущите данни в нея остават недокоснати, просто се свързвате към нея. Ако изберете „Презапиши", съществуващият файл ще бъде безвъзвратно заменен с вашата текуща база данни.'
        });
        if (response === 0) return { ok: false, error: 'Отказано от потребителя.' };
        doCopy = (response === 2);
      }

      /* Редът тук е важен — същият модел като performRestore() в handlers/backup.js.
         Досега базата се затваряше ПРЕДИ копирането: ако копирането се провалеше
         (мрежов дял само за четене, пълен диск, изчезнала папка), програмата
         оставаше жива, но със ЗАТВОРЕНА база — всяко следващо действие гърми с
         „The database connection is not open", а рестарт няма, защото config.json
         не е записан. Сега копието се прави настрани (в ЦЕЛЕВАТА папка, за да е
         преименуването на същото устройство — атомарно), докато базата още работи;
         базата се затваря чак когато новият файл вече е на мястото си. Провал на
         който и да е етап оставя работеща база и непроменена настройка. */
      /* РЕДЪТ В СЛЕДАТА СЕ ПИШЕ ТУК — ПРЕДИ wal_checkpoint и копирането (Б21).
         Така при ПРЕНАСЯНЕ (doCopy) той влиза в контролната точка и пътува с
         копието: новата база отваря следата си точно с него. При „Ползвай
         съществуващата база“ редът остава в изоставената база и се вписва
         отделно в целевата по-долу — тя е друг регистър и трябва да знае от
         кога и откъде се ползва. */
      const who = (typeof deps.getCurrentUser === 'function' ? (deps.getCurrentUser() || '') : '');
      noteInLiveDb('Папка на базата данни', doCopy
        ? 'Базата данни беше ПРЕМЕСТЕНА от „' + path.dirname(oldPath) + '“ в „' + newDir + '“'
          + (fs.existsSync(newPath) ? ' (съществуващият там файл library.db беше заменен по изричен избор)' : '')
          + '. Старият файл остава на мястото си, докато не бъде изтрит ръчно; резервните копия се пренасят '
          + 'заедно с базата. Програмата се стартира наново и оттук нататък работи с базата в новата папка.'
        : 'Програмата беше ПРЕВКЛЮЧЕНА към СЪЩЕСТВУВАЩАТА база данни в „' + newDir + '“ — обикновено общата '
          + 'мрежова база на библиотеката. Данните в нея остават недокоснати, а базата в „'
          + path.dirname(oldPath) + '“ спира да се ползва от този компютър (файлът ѝ остава на мястото си). '
          + 'След рестарта фондът, читателите и заеманията на екрана са тези на новата база.');
      const db = getDb();
      if (db) db.pragma('wal_checkpoint(TRUNCATE)');
      if (doCopy && fs.existsSync(oldPath)) {
        const stagedPath = newPath + '.copy-tmp';
        try {
          fs.copyFileSync(oldPath, stagedPath);
          fs.renameSync(stagedPath, newPath);
        } catch (err) {
          try { if (fs.existsSync(stagedPath)) fs.unlinkSync(stagedPath); } catch (e) { /* нищо за чистене */ }
          /* КОРИГИРАЩ РЕД В СЛЕДАТА (v2.4.65). Редът „Базата данни беше
             ПРЕМЕСТЕНА…“ по-горе нарочно се пише ПРЕДИ копирането — така
             копието в новата папка го наследява и знае откъде идва. Но ако
             копирането падне, живата база остава с ред, който твърди преместване,
             което не се е случило — и проверяващ, който чете следата, ще търси
             регистъра не там, където е. Следата не се трие (тя е документ по
             чл. 17, ал. 2), затова се ДОПЪЛВА: следващият ред казва, че
             опитът е неуспешен и базата е останала тук. */
          try {
            noteInLiveDb('Папка на базата данни', 'ОПИТЪТ ЗА ПРЕМЕСТВАНЕ НЕ УСПЯ — предходният ред за преместване '
              + 'в „' + newDir + '“ НЕ е изпълнен. Базата данни остава в „' + path.dirname(oldPath)
              + '“ и програмата продължава да работи с нея. Причина: ' + err.message);
          } catch (e) { /* следата не бива да прикрива истинската грешка по-долу */ }
          return { ok: false, error: 'Базата данни не можа да бъде копирана в избраната папка — нищо не е променено '
            + 'и програмата продължава да работи с текущата база. Грешка: ' + err.message };
        }
      }
      /* И РЕЗЕРВНИТЕ КОПИЯ. Дотук се пренасяше само library.db, а подпапката
         backups/ оставаше до старото място — при това мълчаливо. Програмата
         веднага след рестарта започва да чете и пише копия в НОВАТА папка
         (backupsDir() е „backups“ до текущата база), тоест списъкът в
         „Настройки“ → „Резервни копия“ осъмва празен, а тридесетдневната
         история виси в стара папка, за която никой не знае. Точно в случая, за
         който смяната на папката е измислена — преместване на базата на нов
         компютър или на мрежов диск, преди старият да бъде изхвърлен — това
         означава изтрита история на копията.
         Копира се (не се мести): старите файлове остават, докато човек сам не
         реши да ги изтрие. Провалът тук НЕ отменя преместването на базата —
         казва се къде са останали копията, което е по-полезно от отказ. */
      const oldBackups = path.join(path.dirname(oldPath), 'backups');
      const newBackups = path.join(newDir, 'backups');
      let movedBackups = 0;
      const failedBackups = [];
      /* Само когато базата наистина се ПРЕНАСЯ. При „Ползвай съществуващата база
         от тази папка“ в целевата папка живее ДРУГА библиотека — копия от нашата
         там само биха подвели кой какво възстановява. */
      if (doCopy && fs.existsSync(oldBackups) && path.resolve(oldBackups) !== path.resolve(newBackups)) {
        try {
          fs.mkdirSync(newBackups, { recursive: true });
          for (const f of fs.readdirSync(oldBackups)) {
            if (!/\.(db|invbak)$/.test(f)) continue; // .tmp огризки не се пренасят
            const dest = path.join(newBackups, f);
            try {
              if (fs.existsSync(dest)) continue; // вече е там (споделена папка от друг компютър)
              const staged = dest + '.copy-tmp';
              fs.copyFileSync(path.join(oldBackups, f), staged);
              fs.renameSync(staged, dest);
              movedBackups++;
            } catch (e) {
              failedBackups.push(f);
              try { if (fs.existsSync(dest + '.copy-tmp')) fs.unlinkSync(dest + '.copy-tmp'); } catch (e2) { /* нищо за чистене */ }
            }
          }
        } catch (err) {
          failedBackups.push('(папката не можа да бъде създадена: ' + err.message + ')');
        }
        if (failedBackups.length && typeof dialog.showMessageBox === 'function') {
          /* Показва се ПРЕДИ рестарта — след app.exit(0) няма кой да го каже.
             Съобщението дава точния път, а не общо „някои файлове не се копираха“:
             копията са единственият изход при повреда и човек трябва да знае къде
             са останали. */
          await dialog.showMessageBox(getMainWindow(), {
            type: 'warning',
            buttons: ['Разбрах'],
            title: 'Част от резервните копия останаха на старото място',
            message: movedBackups + ' от резервните копия бяха пренесени, но ' + failedBackups.length
              + ' не можаха да бъдат копирани.',
            detail: 'Базата данни е преместена успешно и програмата ще се стартира наново.\n\n'
              + 'Останалите копия са в папката:\n' + oldBackups + '\n\n'
              + 'Пренесете ги ръчно в:\n' + newBackups + '\n\n'
              + 'Непренесени файлове: ' + failedBackups.join(', ')
          });
        }
      }
      /* Настройката се записва ПРЕДИ базата да бъде затворена. Обратният ред е
         капан: `updateConfig` се проваля точно в случая, за който е писан —
         нечетим config.json, защото антивирусна програма държи файла — а дотогава
         връзката вече е затворена и рестарт няма да последва. Резултатът беше
         затворена база под съобщение „Базата остава на старото място“: всеки
         следващ екран гърми с техническа грешка, докато програмата не бъде
         спряна и пусната наново.
         updateConfig, а не readConfig+writeConfig: второто при неуспешен прочит
         записва обект само с dbFolder и мълчаливо трие всичко останало. */
      if (!updateConfig((cfg) => { cfg.dbFolder = newDir; })) {
        return { ok: false, error: 'Настройките (config.json) не можаха да бъдат прочетени или записани, затова '
          + 'новата папка НЕ беше запомнена. Базата остава на старото място и програмата продължава да работи '
          + 'нормално. Ако до config.json се е появил файл config.bad.json, той е копие на повредения файл.' };
      }
      /* „Ползвай съществуващата база“: целевата база е ДРУГ регистър и редът от
         горе не е в нея (нищо не е копирано). Пише се направо в нея — иначе
         единственият екран, на който после се търси обяснение за сменения фонд,
         мълчи. При пренасяне това вече е излишно: редът пътува с копието. */
      if (!doCopy) {
        noteInDbFile(newPath, 'Папка на базата данни',
          'От тази дата тази база данни се ползва и от компютъра, на който преди това е работила базата в „'
          + path.dirname(oldPath) + '“. Превключването е направено от „Настройки“ → „Копия и мрежа“ → '
          + '„Папка на базата данни“ с изрично потвърждение „Ползвай съществуващата база от тази папка“ — '
          + 'данните в тази база не са променяни от превключването.', who);
      }
      if (db) db.close();
      app.relaunch();
      app.exit(0);
      return { ok: true, data: newDir };
    } catch (err) {
      return { ok: false, error: err.message };
    }
  });
  ipcMain.handle('dbLocation:resetDefault', () =>
    run(() => {
      const fromDir = resolveDbDir();
      const who = (typeof deps.getCurrentUser === 'function' ? (deps.getCurrentUser() || '') : '');
      /* Редът в ИЗОСТАВЯНАТА база се пише ПРЕДИ промяната на настройката —
         тя вече няма да бъде отваряна и е последната възможност (Б21). */
      noteInLiveDb('Папка на базата данни',
        'Програмата беше върната към СТАНДАРТНАТА папка за база данни. Базата в „' + fromDir
        + '“ спира да се ползва от този компютър — файлът ѝ остава непроменен на мястото си. '
        + 'ВНИМАНИЕ: нищо не се копира. След рестарта на екрана е базата от стандартната папка '
        + '(ако там няма такава, програмата започва с ПРАЗНА нова база). Резервните копия на старата '
        + 'база остават в нейната подпапка „backups“.');
      // Виж бележката при dbLocation:setFolder по-горе.
      if (!updateConfig((cfg) => { delete cfg.dbFolder; })) {
        throw new Error('Настройките (config.json) не можаха да бъдат прочетени — папката НЕ беше върната '
          + 'към стандартната. Копието на повредения файл е до него (config.bad.json).');
      }
      /* Стандартната папка се чете СЛЕД updateConfig — dbFolder вече го няма,
         тоест resolveDbPath() дава именно базата, която ще бъде отворена. */
      const back = resolveDbPath();
      if (path.resolve(back) !== path.resolve(path.join(fromDir, 'library.db'))) {
        noteInDbFile(back, 'Папка на базата данни',
          'От тази дата програмата на този компютър отново работи с тази (стандартна) база данни. '
          + 'Дотогава е работила с базата в „' + fromDir + '“ — тя остава непроменена там и НЕ е пренасяна '
          + 'насам. Всичко, вписано в нея, е в нея.', who);
      }
      app.relaunch();
      app.exit(0);
    })
  );
};
