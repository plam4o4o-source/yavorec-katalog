// Инвентаризация — извадени от main.js в отделен модул (Фаза 4, стъпка 24).
// Зависи от pctRequired/naturalLoss (стабилни function declarations в
// main.js, hoisted) и getDb/run/logAudit.
module.exports = function registerInventorySessionsHandlers(ipcMain, deps) {
  const { getDb, run, logAudit, pctRequired, naturalLoss, normalizeScanCode } = deps;
  const { parseRegisterNo, resolveScannedBook, isValidIsoDate } = require('../security-utils');
  /* Ключът „налично днес“ живее на едно място — db/fund-sql.js. Инвентаризацията
     е точно неговият случай: въпросът по чл. 40 е „какво да проверя ФИЗИЧЕСКИ“,
     а не „какво пише в регистъра към дата“. NULL статусът (стар внос) е във
     фонда — това е и причината условието да не се пише на ръка тук. */
  const { fundByStatus, fundByStatusPlain, QTY_JOIN, FROM_BOOKS_INV } = require('../db/fund-sql');
  /* Името на състоянието „изгубен“ идва от db/enum-triggers.js, а не като
     литерал тук — там е списъкът позволени стойности за books.status и там е
     обяснено защо „изгубен“ и „липсващ“ са две различни неща (чл. 30, т. 5
     срещу т. 6). Преписан литерал би се разминал с тригера при преименуване. */
  const { BOOK_STATUS_LOST } = require('../db/enum-triggers');

  /* ИНВЕНТАРИЗАЦИЯТА БРОИ БИБЛИОТЕЧНИ ДОКУМЕНТИ, НЕ РЕДОВЕ (v2.4.61).
     =====================================================================
     ЗАВАРЕНОТО. Целият този модул броеше РЕДОВЕ в books — един инвентарен
     номер = една единица. Това е вярно за всеки запис, създаден от програмата
     (тя дава по един инвентарен номер на екземпляр), но НЕ е вярно за
     заварените и внесените бази: там един ред може да носи inventory.quantity
     = 3, тоест три библиотечни документа под един номер.

     ЗАЩО БЕШЕ ГРЕШНО. Два документа за едно и също събитие излизаха от
     принтера с различни числа. Измерено върху стар запис с 3 екземпляра по
     4.00 € и още един документ за 3.50 €:

       протокол по чл. 40 (този модул) : „Липсващи: 3 … ОБЩО 3 документа — 16.50 €“
       акт по чл. 30, т. 6 (същите книги): „4 библиотечни документа … 15.50 €“

     Актът се ражда ОТ протокола (бутонът „Проект за акт от липсите“ по-долу),
     тоест проверяващият слага двата листа един до друг и вижда две различни
     истини за една и съща проверка. И двете броения се позовават на едно и
     също нещо: чл. 40 – 41 говорят за библиотечни документи, както и чл. 13 и
     чл. 16. Точно това е записано и в db/fund-sql.js — единственият източник
     на фондовата аритметика: „БРОЯТ Е ПО ДОКУМЕНТИ, НЕ ПО ЗАГЛАВИЯ“.

     ЗАЩО ПОПРАВКАТА Е ТОЧНО ТАЗИ. Пулът, проверените, заетите, тези за
     реставрация и липсващите се смятат по правилото COALESCE(quantity, 1) —
     същото, което db/fund-sql.js държи за целия фонд (QTY_JOIN се ползва
     дословно там, където заявката допуска съединение). Така четирите числа в
     протокола продължават да се СЪБИРАТ до обхвата (изискване, заковано още в
     v2.4.24), но вече в мярката, в която ги чете и актът, и КДБФ, и
     инвентарната книга. Нормативът по чл. 41 се прилага към същата мярка —
     иначе „допустими 0.5 документа“ би се сравнявало с липси, изброени в
     редове.

     БРОЙКАТА СЕ СНИМА, НЕ СЕ ЧЕТЕ НАЖИВО. При приключването бройката на всеки
     липсващ документ се записва в inventory_session_missing.quantity — точно
     както deaccession_items.quantity пази бройката в акта (чл. 35, ал. 2).
     Иначе поправка на „Налични бройки“ на вече липсващ документ би променила
     ВЕЧЕ ОТПЕЧАТАНИЯ и подписан протокол със задна дата. Заварените редове
     (проверки, приключени преди v2.4.61) нямат снимка и за тях се чете живата
     бройка — COALESCE в inventorySessions:get; за тях снимка няма откъде да
     се вземе. */
  const QTY_MISSING = 'COALESCE(inv.quantity, 1)';

  ipcMain.handle('inventorySessions:list', () =>
    run(() => getDb().prepare(`
      SELECT s.*,
             /* Приключена проверка показва СНИМКАТА (scanned_final) — същото
                число, което влиза и в протокола по чл. 40. Иначе списъкът
                показваше суровия брой сканирания до самия бутон „Протокол“,
                който печата поправеното: „в обхвата 9 · проверени 7 · липсващи
                4“ на екрана срещу „проверени 6“ на хартия (проверка при
                прегледа на v2.4.45). Текуща проверка и сесиите отпреди
                снимката имат NULL и се броят както досега.
                Текущата проверка вече се брои в ДОКУМЕНТИ (виж бележката
                по-горе) — иначе редът в списъка и протоколът, до който води
                бутонът на същия ред, пак биха се разминали. */
             COALESCE(s.scanned_final,
                      (SELECT COALESCE(SUM(${QTY_MISSING}), 0) FROM inventory_session_scans sc
                         LEFT JOIN inventory inv ON inv.book_id = sc.book_id
                        WHERE sc.session_id = s.id)) AS scanned,
             /* СЪЩАТА СНИМКА, КОЯТО ЧЕТЕ И ПРОТОКОЛЪТ (поправка след прегледа на
                кръга). Дотук този ред сумираше ЖИВАТА бройка, а
                inventorySessions:get и протоколът по чл. 40 — записаната
                m.quantity. Едно поправено „Налични бройки“ на вече липсващ
                документ разминаваше екрана и хартията за една и съща проверка:
                „липсващи 1“ в списъка срещу „липсващи 3“ в подписания протокол.
                COALESCE-ът пази заварените редове без снимка — за тях живата
                бройка е единственото, което има. */
             (SELECT COALESCE(SUM(COALESCE(m.quantity, ${QTY_MISSING})), 0) FROM inventory_session_missing m
                LEFT JOIN inventory inv ON inv.book_id = m.book_id
               WHERE m.session_id = s.id) AS missing,
             /* Редовете се връщат ОТДЕЛНО: екранът казва „5 документа (3 записа)“
                само когато двете числа се разминават, вместо да мълчи за разликата. */
             (SELECT COUNT(*) FROM inventory_session_missing m WHERE m.session_id = s.id) AS missing_rows
      FROM inventory_sessions s ORDER BY s.date DESC
    `).all())
  );
  ipcMain.handle('inventorySessions:requirement', () =>
    run(() => {
      const db = getDb();
      // Одит v2.3.1 №20: `status != 'отчислен'` в SQL дава NULL (не TRUE) за ред с
      // NULL status и SQLite мълчаливо го изключва от WHERE — книга с NULL status
      // (стари/внесени данни, никога прегледани) изчезваше от пула за инвентаризация,
      // докато ЕДНОВРЕМЕННО публичният каталог я броеше за налична (виж #9,
      // main.js: publicBookFields) — пропада през двете предпазни мрежи едновременно.
      // Условието включва изрично и NULL редовете навсякъде тук, където се смята пул.
      /* Мярката е РЕДОВЕ (инвентарни номера), не екземпляри — съзнателно и
         документирано решение, виж дългата бележка в handlers/dashboard.js:
         инвентаризацията се проверява чрез сканиране, а инвентарният номер в тази
         схема е един на ред в books. Двата екрана ТРЯБВА да ползват една и съща
         мярка, иначе Таблото и „Инвентаризация“ показват различни цели.

         Одит v2.4.16 отбеляза, че числото се ПОКАЗВАШЕ с етикет „Библиотечен
         фонд“ — същия, с който Таблото нарича броя екземпляри. Числата са две
         различни неща и не бива да носят едно име; поправено е в етикета
         (src/views/inventory-sessions.js), не в мярката. */
      const active = db.prepare(`SELECT COUNT(*) AS n FROM books WHERE ${fundByStatusPlain}`).get().n;
      /* СЪЩИЯТ ФОНД, НО В ДОКУМЕНТИ (v2.4.61). Мярката на НОРМАТА по чл. 40,
         т. 2 остава инвентарни номера — виж дългата бележка точно отгоре и
         handlers/dashboard.js: проверката се прави чрез сканиране на номер и
         Таблото мери същото. Но нормативът по чл. 41 (допустим отпад) се
         сравнява с ЛИПСИТЕ, а те от тази версия се броят в библиотечни
         документи (виж заглавната бележка на модула). Ако тук останеше старото
         `naturalLoss(active, …)`, екранът щеше да показва един допустим отпад,
         а подписаният протокол за същата проверка — друг. Затова числото за
         чл. 41 се смята от ДОКУМЕНТИТЕ, а числото за нормата — от номерата, и
         двете се връщат отделно, за да може екранът да каже кое какво е. */
      const activeDocs = db.prepare(`SELECT COALESCE(SUM(${QTY_JOIN}), 0) AS n ${FROM_BOOKS_INV}
        WHERE ${fundByStatus}`).get().n;
      const s = db.prepare('SELECT free_access_pct FROM settings WHERE id = 1').get();
      const pct = pctRequired(active);
      /* Напредъкът за ГОДИНАТА се смята тук, а не чрез сумиране на сесиите в
         екрана: един и същ документ, проверен в пролетна и в есенна сесия, се
         броеше два пъти и екранът можеше да обяви нормата за изпълнена при
         неизпълнена. Същата поправка вече беше направена за Таблото
         (handlers/dashboard.js), но не и тук — класическото „поправено на едно
         от две места“. */
      const y = String(new Date().getFullYear());
      /* ЕКРАНЪТ И ПРОТОКОЛЪТ БРОЯТ ЕДНО И СЪЩО (v2.4.57).
         =================================================================
         Дотук тази заявка броеше СУРОВИТЕ сканирания за годината, а
         inventorySessions:close брои „проверени“ СРЕЩУ ОБХВАТА — тоест изважда
         документите, излезли от обхвата, докато проверката е текла (виж
         outOfScope там). Двете числа се разминават при най-обикновено събитие:
         документ, сканиран от комисията и отчислен с акт СЪЩИЯ месец.

         Измерено върху една книга и една сесия: екранът обявяваше нормата по
         чл. 40 за изпълнена — „проверени 1 от 1“ — а подписаният протокол за
         същата тази сесия гласеше „проверени 0“. Числото на екрана е това, по
         което библиотекарката решава дали да продължи да проверява; протоколът
         е това, което се подписва. Да се разминават е по-лошо от това и двете
         да са приблизителни.

         Условието е СЪЩОТО, което дава `active` два реда по-горе и `pool` в
         close() — затова идва от db/fund-sql.js, а не се преписва: три копия на
         едно правило са начинът, по който то се разпада. DISTINCT остава заради
         пролетната и есенната сесия (виж бележката по-горе). */
      const scannedYear = db.prepare(`
        SELECT COUNT(DISTINCT sc.book_id) AS n FROM inventory_session_scans sc
        JOIN inventory_sessions s ON s.id = sc.session_id
        JOIN books b ON b.id = sc.book_id
        WHERE substr(s.date,1,4) = ? AND ${fundByStatus}
      `).get(y).n;
      return { active, activeDocs, pct, target: Math.ceil(active * pct / 100), scannedYear,
        naturalLoss: naturalLoss(activeDocs, s.free_access_pct) };
    })
  );
  ipcMain.handle('inventorySessions:start', (e, s) =>
    run(() => {
      /* Датата се проверява като при акта и партидата (одит v2.4.25). Дотук
         изчистено поле пращаше '' — NOT NULL го приема — сесията се записваше без
         дата, всяко сканиране пишеше inventory_checks.date = '' и не се броеше към
         годишната норма, а протоколът печаташе „Днес,  г., комисия…“. */
      if (!isValidIsoDate(s && s.date)) throw new Error('Датата на проверката липсва или е невалидна.');
      const db = getDb();
      // Одит v2.3.1 №20 — виж бележката в inventorySessions:requirement по-горе.
      /* Обхватът се снима в ДОКУМЕНТИ (v2.4.61) — същата мярка, с която
         приключването смята pool_final и с която протоколът по чл. 40 брои
         липсите. Дотук тук се броеше COUNT(*), тоест текущата проверка
         показваше „В обхвата 8“, а протоколът за същата проверка — 10.
         Условието и изразът за бройката идват от db/fund-sql.js. */
      const pool = db.prepare(`SELECT COALESCE(SUM(${QTY_JOIN}), 0) AS n ${FROM_BOOKS_INV}
        WHERE ${fundByStatus} ${s.department ? 'AND b.department = @department' : ''}`)
        .get(s.department ? { department: s.department } : {});
      /* Номер и година на протокола. Точно както при партидите (acquisitions:create):
         schema.sql няма UNIQUE(year, no) и не може да го получи наготово — съществуващи
         бази може вече да носят дубликати и миграцията би счупила стартирането. Затова
         номерът се ИЗБИРА и се ПРОВЕРЯВА вътре в транзакция с .immediate(): правото на
         запис се взима ПРЕДИ проверката, тоест между нея и INSERT-а никой друг не може
         да вмъкне същия номер.
         Одит v2.4.18 (преглед на поправките от v2.4.17): дотук коментарът тук твърдеше,
         че „проверката се повтаря в записа“, а такава проверка нямаше — нито транзакция.
         Две работни места към обща мрежова база (изрично поддържан режим) получаваха
         един и същ MAX(no)+1 и издаваха ДВА протокола по чл. 40 с номер № N/година;
         ръчно въведен вече зает номер минаваше също така мълчаливо. */
      const year = String(s.date || '').slice(0, 4) || String(new Date().getFullYear());
      /* Празно поле → следващият свободен; въведено число → точно то, проверено.
         Дотук `parseInt(s.no) || MAX+1`: въведена нула пропадаше през || и ставаше
         следващият номер без дума, „-3“ и „1.5“ минаваха. Проверката е ПРЕДИ
         транзакцията — правото на запис не се взима заради невалиден вход. */
      const typed = parseRegisterNo(s.no, 'Протокол №', true);
      const tx = db.transaction(() => {
        const no = typed
          || ((db.prepare('SELECT MAX(no) AS m FROM inventory_sessions WHERE year = ?').get(year).m || 0) + 1);
        if (db.prepare('SELECT 1 FROM inventory_sessions WHERE year = ? AND no = ?').get(year, no)) {
          throw new Error('Протокол № ' + no + '/' + year + ' вече съществува — най-вероятно е създаден от друго '
            + 'работно място към същата база. Затворете и отворете формата отново, за да получите следващия свободен номер.');
        }
        const info = db.prepare(`
          INSERT INTO inventory_sessions (date, scope, department, committee1, committee2, committee3,
                                          pool_size, closed, no, year, order_no)
          VALUES (@date, @scope, @department, @committee1, @committee2, @committee3, @pool_size, 0, @no, @year, @order_no)
        `).run(Object.assign({}, s, {
          department: s.department || null, pool_size: pool.n, no, year, order_no: s.order_no || null
        }));
        return info.lastInsertRowid;
      });
      return tx.immediate();
    })
  );
  ipcMain.handle('inventorySessions:get', (e, id) =>
    run(() => {
      const db = getDb();
      const s = db.prepare('SELECT * FROM inventory_sessions WHERE id = ?').get(id);
      if (!s) return null;
      /* Бройката пътува с всеки ред (v2.4.61): екранът „проверка в ход“ и
         протоколът броят библиотечни документи, а не редове — виж заглавната
         бележка на модула. Стар запис с inventory.quantity = 3 е един сканиран
         ред, но три проверени документа. */
      s.scans = db.prepare(`
        SELECT sc.*, b.inv_number, b.title, ${QTY_MISSING} AS quantity FROM inventory_session_scans sc
        JOIN books b ON b.id = sc.book_id
        LEFT JOIN inventory inv ON inv.book_id = sc.book_id
        WHERE sc.session_id = ? ORDER BY sc.scanned_at DESC
      `).all(id);
      /* Подредбата е по инвентарен номер — така се чете списъкът на липсите в
         протокола и така се сверява с рафта. Дотук редовете излизаха в реда, в
         който приключването ги е вписало (ред на таблицата books). */
      /* on_loan_now (v2.4.67): колко бройки на същия запис са у читател В МОМЕНТА.
         Частично зает стар запис влиза в липсите само с ненамерените си бройки;
         „Проект за акт от липсите“ трябва да знае това, за да не отчисли и
         бройката, която читателят още държи (виж draftFromMissing). */
      s.missing = db.prepare(`
        SELECT m.*, COALESCE(m.quantity, ${QTY_MISSING}) AS quantity,
               (SELECT COUNT(*) FROM loans l WHERE l.book_id = m.book_id AND l.date_in IS NULL) AS on_loan_now,
               inv.quantity AS live_qty
        FROM inventory_session_missing m
        LEFT JOIN inventory inv ON inv.book_id = m.book_id
        WHERE m.session_id = ? ORDER BY m.inv_number, m.id
      `).all(id);
      /* Двете числа за липсите: документи (мярката по чл. 40 – 41) и редове
         (колко инвентарни номера са изброени в таблицата на протокола). */
      s.missingDocs = s.missing.reduce((n, m) => {
        const q = Number(m.quantity);
        return n + (Number.isFinite(q) && q >= 0 ? q : 1);
      }, 0);
      /* Допустимите естествени загуби по чл. 41 се смятат ТУК, за да може протоколът
         да ги отпечата. Одит на документите v2.4.17: приключването ги връщаше,
         прозорецът ги показваше и сравняваше с тях, екранът ги показваше — а
         документът, който излиза от сградата, ги нямаше. Тоест единственият въпрос,
         на който протоколът съществува да отговори (в рамките на допустимото ли са
         липсите), беше неотговорим от хартията. */
      /* Процентът — снимката от приключването (v2.4.67, миграция 17); текущата
         настройка само за неприключена сесия. Иначе смяна на настройката по-късно
         пренаписва норматива на вече подписан протокол. */
      const cfg = db.prepare('SELECT free_access_pct FROM settings WHERE id = 1').get() || {};
      const pct = s.free_access_pct != null ? s.free_access_pct : cfg.free_access_pct;
      const poolForLoss = s.pool_final != null ? s.pool_final : (s.pool_size || 0);
      s.allowedLoss = naturalLoss(poolForLoss, pct);
      /* ИЗГУБЕНИТЕ ОТ ПОЛЗВАТЕЛИ — СОБСТВЕН РЕД В ПРОТОКОЛА (v2.4.65).
         =================================================================
         Приключването вече ги извинява отделно (виж дългата бележка в
         inventorySessions:close), но протоколът по чл. 40 трябва да ги ОБЯВИ:
         иначе четирите числа на листа („в обхвата · проверени · заети · за
         реставрация · липсващи“) вече не се събират до обхвата и разликата
         изглежда като необяснима дупка точно в документа, който проверяващият
         сравнява с рафта.

         Числото се ИЗВЕЖДА от снимките, а НЕ се чете наживо от books и НЕ се
         записва в нова колона. Причините са две:
           • Наживо е грешно: изгубен документ, отчислен с акт по чл. 30, т. 5
             месец след проверката, би изчезнал от вече отпечатан и подписан
             протокол — точно дефектът, срещу който са писани pool_final,
             scanned_final и inventory_session_missing.quantity.
           • Нова колона в inventory_sessions е промяна в схемата (db/schema.sql),
             а тя не се прави мимоходом — докладва се. Тук не е нужна: и петте
             члена на равенството вече са снимки, значи и остатъкът е снимка.
         Равенството е това, което приключването пази изрично:
           в обхвата = проверени + заети + за реставрация + изгубени + липсващи.
         Смята се САМО за пълна проверка: при представителната несканираните не
         са липсващи и остатъкът смесва изгубените с невлезлите в извадката.
         Проверките, приключени ПРЕДИ тази версия, дават остатък 0 (изгубените
         тогава са в липсите) — редът просто не се печата, вместо протоколът да
         твърди „0 изгубени“. Отрицателен остатък (повредена или ръчно пипана
         база) се показва като липсващо число, а не като отрицателен брой. */
      if (s.mode === 'full' && s.pool_final != null && s.scanned_final != null
          && s.on_loan != null && s.at_binder != null) {
        const rest = s.pool_final - s.scanned_final - s.on_loan - s.at_binder - s.missingDocs;
        s.lostBefore = rest > 0 ? rest : 0;
      } else {
        s.lostBefore = null;
      }
      return s;
    })
  );
  // normalizeScanCode() (v1.70.1) — виж books:byBarcode в handlers/books.js за
  // обяснението на кирилско/латинско разминаване при баркод четец.
  ipcMain.handle('inventorySessions:scan', (e, { sessionId, code }) =>
    run(() => {
      const db = getDb();
      const s = db.prepare('SELECT * FROM inventory_sessions WHERE id = ?').get(sessionId);
      if (!s || s.closed) throw new Error('Няма отворена сесия за инвентаризация.');
      const c = normalizeScanCode(code);
      // Одит v2.4.24 — виж resolveScannedBook() в security-utils.js: иначе
      // протоколът отбелязваше като „проверен" ДРУГ документ, а истинският
      // оставаше в липсите.
      const b = resolveScannedBook(db, c);
      if (!b) throw new Error('Непознат баркод/инв. № ' + code);
      /* Одит v2.4.14: тук се приемаше и ОТЧИСЛЕН документ, за разлика от
         deaccessionActs:findBook, който изрично го изключва. Пулът, спрямо който
         се смята нормата (inventorySessions:start), брои само неотчислените —
         тоест отчислен документ вдигаше числителя, без да е в знаменателя. */
      if (b.status === 'отчислен') {
        throw new Error('Инв. № ' + b.inv_number + ' е отчислен и не е част от фонда, който тази проверка обхваща. '
          + 'Документът не е записан в протокола.');
      }
      /* Одит v2.3.1 №24: сесия, ограничена до един отдел (s.department), тихо
         приемаше сканирания на книги от ДРУГИ отдели — броени като „проверени“ в
         протокола, макар да са извън декларирания обхват/pool_size (последният е
         преброен САМО за отдела при inventorySessions:start). Отказва се изрично,
         вместо да се приема мълчаливо — протоколът пред регионалната библиотека
         трябва да отговаря точно на обявения обхват. */
      if (s.department && (b.department || '') !== s.department) {
        throw new Error('Инв. № ' + b.inv_number + ' е от отдел „' + (b.department || '—') +
          '“, а тази инвентаризация обхваща само отдел „' + s.department + '“. Документът не е записан в протокола.');
      }
      /* Четирите записа минават ЗАЕДНО или никак. Одит v2.4.14: дотук бяха
         четири отделни изявления извън транзакция, докато всички съседни
         handler-и ползват .immediate() — при SQLITE_BUSY по средата (обичайно на
         мрежова база) протоколът и картонът на книгата се разминаваха.
         Уникалният индекс от миграция v8 пази същото и на ниво база: проверката
         „вече е сканиран“ в JavaScript не е достатъчна, когато две станции
         сканират едновременно. */
      const tx = db.transaction(() => {
        const already = db.prepare('SELECT 1 FROM inventory_session_scans WHERE session_id = ? AND book_id = ?').get(sessionId, b.id);
        if (already) throw new Error('Инв. № ' + b.inv_number + ' вече е сканиран.');
        db.prepare('INSERT INTO inventory_session_scans (session_id, book_id) VALUES (?, ?)').run(sessionId, b.id);
        db.prepare('INSERT INTO inventory_checks (book_id, date) VALUES (?, ?)').run(b.id, s.date);
        db.prepare("UPDATE books SET datelastseen = datetime('now') WHERE id = ?").run(b.id);
        if (b.status === 'липсващ') db.prepare("UPDATE books SET status='наличен', status_date=date('now', 'localtime') WHERE id=?").run(b.id);
      });
      try { tx.immediate(); } catch (err) {
        // Дубликат, спрян от уникалния индекс (другата станция ни е изпреварила).
        if (/UNIQUE constraint failed: inventory_session_scans/.test(err.message)) {
          throw new Error('Инв. № ' + b.inv_number + ' вече е сканиран (записан е от другото работно място).');
        }
        throw err;
      }
      /* Бройката се връща на екрана (v2.4.61): броячът „Намерени“ се вдига на
         място, без пречертаване (иначе дневникът на сканиранията се трие), и
         трябва да върви с мярката на протокола — библиотечни документи. */
      const qty = db.prepare('SELECT COALESCE(quantity, 1) AS q FROM inventory WHERE book_id = ?').get(b.id);
      return { inv_number: b.inv_number, title: b.title, quantity: qty ? qty.q : 1 };
    })
  );
  /* Приключване на сесията. `mode` е задължителен избор на библиотекаря:

     'full'          — ПЪЛНА проверка: всичко несканирано (и незаето) се смята за
                       липсващо, вписва се в протокола и получава статус „липсващ".
     'representative'— ПРЕДСТАВИТЕЛНА проверка по чл. 40, т. 2 (минимум 10% годишно):
                       протоколът важи САМО за сканираното; несканираното НЕ се пипа.

     До v2.1.0 разлика нямаше — close() винаги се държеше като 'full'. А самата
     програма представя проверката като представителна (полето „Обхват" е
     предпопълнено с този текст, таблото мери напредък към 10% цел), затова
     библиотекар, изпълнил ТОЧНО нормативното изискване и натиснал „Приключи",
     получаваше протокол с 90% липси и презаписани статуси на почти целия фонд —
     връщането им беше само ръчно, книга по книга. Проверено: 100 книги, сканирани
     целевите 10 → 90 маркирани „липсващ".

     Стойността по подразбиране НЕ е 'full': по-безопасно е приключване без изричен
     избор да не пипа статуси, отколкото да ги презапише масово. */
  ipcMain.handle('inventorySessions:close', (e, arg) =>
    run(() => {
      const db = getDb();
      // Приема и голо id (стар подпис), и {sessionId, mode} — за съвместимост.
      const sessionId = (arg && typeof arg === 'object') ? arg.sessionId : arg;
      const mode = (arg && typeof arg === 'object' && arg.mode) ? arg.mode : 'representative';
      if (mode !== 'full' && mode !== 'representative') {
        throw new Error('Непознат вид инвентаризация: ' + mode);
      }
      const tx = db.transaction(() => {
        const s = db.prepare('SELECT * FROM inventory_sessions WHERE id = ?').get(sessionId);
        if (!s) throw new Error('Няма такава сесия.');
        if (s.closed) throw new Error('Тази инвентаризация вече е приключена.');
        const scannedIds = db.prepare('SELECT book_id FROM inventory_session_scans WHERE session_id = ?').all(sessionId).map(r => r.book_id);
        /* Одит v2.3.1 №20 — виж бележката в inventorySessions:requirement по-горе.
           Полетата са ИЗБРОЕНИ, а не „*“: приключването ползва шест от тях, а
           таблицата има 38 колони, сред които анотация и адрес на корица.
           Измерено при 15 000 документа — 14 МБ прочетени и разпределени в
           паметта, за да се погледнат шест числа. */
        const pool = db.prepare(`SELECT id, inv_number, title, author, price, status FROM books
          WHERE ${fundByStatusPlain} ${s.department ? 'AND department = ?' : ''}`)
          .all(...(s.department ? [s.department] : []));
        /* БРОЙКИТЕ — ЕДНА ЗАЯВКА ЗА ЦЕЛИЯ ОБХВАТ (v2.4.61).
           Протоколът по чл. 40 – 41 брои библиотечни ДОКУМЕНТИ (виж заглавната
           бележка на модула), тоест на всеки ред трябва inventory.quantity. Тя
           НЕ се съединява към заявката отгоре нарочно: нейната проекция е
           изрично изброена и заварена с тест (test/perf-v2448.test.js) — тя е
           причината приключването да не тегли 14 МБ за шест числа, и не бива да
           се разваля мимоходом. Затова бройките идват отделно, но пак с ЕДНА
           заявка върху същия обхват: `SELECT … FROM inventory` вътре в
           обхождането би било 15 000 компилации на един и същ SQL — точно
           грешката, срещу която е писан онзи тест.
           Редовете БЕЗ запис в inventory (стара или внесена база) не се връщат
           тук и падат на 1 в qtyOf — същото, което прави COALESCE(…, 1) в
           db/fund-sql.js: ред без бройка е поне един документ. */
        const qtyById = new Map(db.prepare(`SELECT i.book_id, i.quantity FROM inventory i
          JOIN books b ON b.id = i.book_id
          WHERE ${fundByStatus} ${s.department ? 'AND b.department = ?' : ''}`)
          .all(...(s.department ? [s.department] : [])).map(r => [r.book_id, r.quantity]));
        /* Мярката на целия протокол: библиотечни документи по чл. 40 – 41.
           Липсваща бройка е един документ; отрицателна или нечислова стойност от
           заварена база се брои за един, за да не вади числа от сбора — изричната
           нула се уважава и си личи в „Настройки“ → „Проверка на данните“. */
        const qtyOf = (b) => {
          const q = Number(qtyById.has(b.id) ? qtyById.get(b.id) : 1);
          return Number.isFinite(q) && q >= 0 ? q : 1;
        };
        const docs = (arr) => arr.reduce((n, b) => n + qtyOf(b), 0);
        /* КОЛКО бройки на документа са заети, а не само ДАЛИ (v2.4.67). Стар
           неразделен запис с 3 бройки и едно отворено заемане се броеше целият като
           „зает“ — възпроизведено: протоколът гласеше „заети 3 · липсващи 0“, а
           двете ненамерени бройки изчезваха от документа по чл. 40. Заетите вече са
           min(отворени заемания, бройки); останалите бройки на несканиран ред са
           непроверени (при пълна проверка — липсващи). */
        const openLoanCount = new Map(db.prepare(
          'SELECT book_id, COUNT(*) AS n FROM loans WHERE date_in IS NULL GROUP BY book_id').all()
          .map(r => [r.book_id, r.n]));
        const openLoanIds = new Set(openLoanCount.keys());
        const loanedOf = (b) => Math.min(openLoanCount.get(b.id) || 0, qtyOf(b));
        const scannedSet = new Set(scannedIds);
        /* Одит v2.4.24: извинени са само заетите. Документ „за реставрация“ е при
           подвързвача — по определение не може да бъде сканиран на място, а
           „за реставрация“ е валидно състояние, което библиотекарят задава изрично
           от картона. Дотук той влизаше в липсите: 3 книги при подвързвача правеха
           протокола „липси над норматива с 2.0 документа — прилага се редът по
           чл. 51 – 53“, а състоянието им се презаписваше на „липсващ“ наведнъж
           (връщането е ръчно, книга по книга). Броят им се връща отделно, за да го
           обяви протоколът, вместо да го скрие. */
        /* Четирите категории трябва да са ВЗАИМНО ИЗКЛЮЧВАЩИ СЕ, иначе протоколът
           не се събира. Документ „за реставрация“ може да е бил върнат от
           подвързвача и сканиран (inventorySessions:scan приема такъв документ и
           нулира само „липсващ“), а може и да е зает — броен два пъти, протоколът
           щеше да гласи „в обхвата 100 · проверени 40 · заети 5 · за реставрация 3 ·
           липсващи 53“, тоест 101 от 100. */
        const excused = pool.filter(b => b.status === 'за реставрация'
          && !scannedSet.has(b.id) && !openLoanIds.has(b.id));
        /* ИЗГУБЕНИЯТ ОТ ЧИТАТЕЛ НЕ Е ЛИПСВАЩ ПРИ ИНВЕНТАРИЗАЦИЯ (v2.4.65).
           =================================================================
           ЗАВАРЕНОТО. Документ, приключен на гишето с „Документът е изгубен“
           (loans:markLost — обезщетението е начислено в сметката на читателя,
           books.status = 'изгубен'), физически го няма в библиотеката: той е у
           ползвателя и не може да бъде сканиран. Дотук той падаше право в
           `unchecked`, оттам в `missing`, а няколко реда по-долу статусът му се
           презаписваше наведнъж на „липсващ“.

           ЗАЩО БЕШЕ ГРЕШНО — три последици от един пропуск:
             • ОСНОВАНИЕТО. „липсващ“ значи „не е намерен при инвентаризация“ и
               води до чл. 30, т. 6; невърнатият от ползвател се отчислява по
               чл. 30, т. 5 („повредени или невърнати от ползватели“). Бутонът
               „Проект за акт от липсите“ в този екран вземаше липсите от
               протокола и предлагаше т. 6 — тоест подписаният акт излизаше на
               грешно основание.
             • НОРМАТИВЪТ. Документът влизаше в протокола по чл. 40 като
               установена липса и се броеше срещу допустимия отпад по чл. 41;
               при малка библиотека няколко такива случая сами по себе си
               вдигат липсите над норматива и задействат реда по чл. 51 – 53 за
               документи, чиято съдба вече е уредена с читателя.
             • ВРЪЗКАТА С ОБЕЗЩЕТЕНИЕТО. Презаписването на статуса изтриваше
               единствения белег, че случаят е уреден: справката „Изгубени /
               невърнати“ и картонът на читателя сочат едно, а фондът — друго.

           Самата програма пише обратното на две места: db/enum-triggers.js
           („липсващ по установената практика значи «не е намерен при
           инвентаризация»… смесването им означава акт, съставен на грешно
           основание“) и test/registri-v2456.test.js. Тоест това беше пропуск,
           а не решение.

           ЗАЩО ПОПРАВКАТА Е ТОЧНО ТАЗИ. Изгубените се извиняват по същия начин
           като заетите и тези за реставрация — не могат да бъдат сканирани на
           място по причина, известна на библиотеката ПРЕДИ проверката, — но в
           СВОЯ категория, за да ги обяви протоколът с името им, вместо да ги
           скрие или да ги смеси с липсите. Статусът им не се пипа: той е
           основанието за акта по чл. 30, т. 5.
           Категориите остават ВЗАИМНО ИЗКЛЮЧВАЩИ СЕ (виж бележката отгоре):
           в обхвата = проверени + заети + за реставрация + изгубени + липсващи. */
        const lostBefore = pool.filter(b => b.status === BOOK_STATUS_LOST
          && !scannedSet.has(b.id) && !openLoanIds.has(b.id));
        const excusedIds = new Set(excused.map(b => b.id).concat(lostBefore.map(b => b.id)));
        const unchecked = pool.filter(b => !scannedSet.has(b.id) && !openLoanIds.has(b.id) && !excusedIds.has(b.id));
        /* Частично заети: несканиран ред с отворени заемания, но с повече бройки от
           тях. Незаетите му бройки не са извинени от нищо — не са намерени. */
        const partlyLoaned = pool.filter(b => !scannedSet.has(b.id) && openLoanIds.has(b.id)
          && !excusedIds.has(b.id) && qtyOf(b) - loanedOf(b) > 0);
        const restOf = new Map(partlyLoaned.map(b => [b.id, qtyOf(b) - loanedOf(b)]));
        /* Бройките, които се водят като непроверени/липсващи за даден ред. */
        const missingQty = (b) => (restOf.has(b.id) ? restOf.get(b.id) : qtyOf(b));
        // При представителна проверка непроверените НЕ са липсващи — те просто не
        // са влизали в обхвата на тазгодишната извадка.
        const missing = mode === 'full' ? unchecked.concat(partlyLoaned) : [];
        /* БРОЙКАТА СЕ СНИМА ЗАЕДНО С ЦЕНАТА И ЗАГЛАВИЕТО (v2.4.61).
           Редът тук е снимка към деня на приключването — затова носи заглавие,
           автор и цена, а не само book_id. Бройката липсваше от снимката и се
           четеше наживо от inventory: поправка на „Налични бройки“ на вече
           липсващ документ променяше вече отпечатания и подписан протокол със
           задна дата. Сега се пази и тя — точно както deaccession_items.quantity
           пази бройката в акта (чл. 35, ал. 2). */
        const insMissing = db.prepare(`
          INSERT INTO inventory_session_missing (session_id, book_id, inv_number, title, author, price, quantity)
          VALUES (?, ?, ?, ?, ?, ?, ?)
        `);
        missing.forEach(b => {
          insMissing.run(sessionId, b.id, b.inv_number, b.title, b.author, b.price, missingQty(b));
        });
        /* Отбелязването като „липсващ“ е ЕДНА заявка върху току-що вписаните редове,
           а не по една на документ. Дотук в обхождането стоеше db.prepare(...) —
           тоест при пълна проверка на фонд от 15 000 документа, в която комисията
           още не е сканирала нищо, 14 000 отделни КОМПИЛАЦИИ на един и същ SQL плюс
           14 000 изпълнения. Измерено: приключването отнемаше 657 ms — почти
           секунда, в която прозорецът стои залепнал, точно при „Приключи“.
           Условието за статуса се пази дословно: то е излишно, защото обхватът и без
           това изключва отчислените, но е предпазна мярка и не се маха мимоходом. */
        if (missing.length) {
          /* Ред с отворено заемане (частично зает стар запис) не се отбелязва като
             „липсващ“ целият: една от бройките му е у читател и връщането ѝ трябва
             да мине нормално. Липсващите му бройки са в протокола с точния брой;
             „Проект за акт от липсите“ разделя стария запис, преди да отчисли. */
          db.prepare(`UPDATE books SET status='липсващ', status_date=date('now', 'localtime')
            WHERE ${fundByStatusPlain}
              AND id IN (SELECT book_id FROM inventory_session_missing WHERE session_id = ?)
              AND id NOT IN (SELECT book_id FROM loans WHERE date_in IS NULL)`)
            .run(sessionId);
        }
        /* Видът се ЗАПИСВА в базата (v2.3.0). Дотогава оставаше само в отговора към
           прозореца, затова в списъка приключена представителна проверка с 0 липсващи
           изглеждаше точно като пълна с 0 липсващи — а пред проверяващ от регионалната
           библиотека няма как да се докаже кое от двете е било. */
        /* Пулът и заетите се ЗАПИСВАТ такива, каквито са в момента на приключване.
           pool_size е снимка от започването; книги, вписани докато проверката тече,
           влизат в `unchecked`/`missing`, но не и в снимката — протоколът можеше да
           гласи „в обхвата 10 · проверени 10 · липсващи 30“. Одит на документите
           v2.4.17. */
        /* Заетите се броят СРЕД НЕПРОВЕРЕНИТЕ, по същата причина като „за реставрация“
           по-горе: четирите числа в протокола трябва да се събират до обхвата.
           Заета книга, която все пак е сканирана (върната на гишето, но още
           нерегистрирана), е ПРОВЕРЕНА — тя е била в ръцете на комисията. */
        const onLoanInPool = pool.filter(b => openLoanIds.has(b.id) && !scannedSet.has(b.id))
          .reduce((n, b) => n + loanedOf(b), 0);
        /* „Проверени“ се брои СРЕЩУ ОБХВАТА, а не като брой сканирания. Обхватът
           се смята наново при приключване (книга, отчислена или преместена в друг
           отдел, докато проверката тече, вече не е в него), а сканиранията са
           всичко, което комисията е минала. Дотук се връщаше суровият брой
           сканирания и четирите числа НАДХВЪРЛЯХА обхвата — точно това, което
           бележката по-горе иска да няма: 10 книги, отчислена една по време на
           проверката, даваше „в обхвата 9 · проверени 6 · липсващи 4“, тоест 10
           от 9 в подписания протокол по чл. 40. Излезлите от обхвата се връщат
           ОТДЕЛНО (outOfScope), за да ги обяви протоколът, вместо да ги скрие. */
        const poolIds = new Set(pool.map(b => b.id));
        /* Сканираното се брои през ПУЛА, а не през списъка с book_id: така
           бройката на всеки проверен документ идва от същия ред, от който идва
           и бройката в обхвата, и „проверени + липсващи + заети + за
           реставрация“ пак се събира точно до обхвата — вече в документи. */
        const scannedInPoolRows = pool.filter(b => scannedSet.has(b.id));
        const scannedInPool = docs(scannedInPoolRows);
        const outOfScope = scannedIds.length - scannedInPoolRows.length;
        const poolDocs = docs(pool);
        const missingDocs = missing.reduce((n, b) => n + missingQty(b), 0);
        const excusedDocs = docs(excused);
        const lostDocs = docs(lostBefore);
        /* Процентът за норматива по чл. 41 се СНИМА тук (v2.4.67) — виж миграция 17. */
        const pctNow = (db.prepare('SELECT free_access_pct FROM settings WHERE id = 1').get() || {}).free_access_pct;
        db.prepare('UPDATE inventory_sessions SET closed = 1, mode = ?, pool_final = ?, on_loan = ?, at_binder = ?, scanned_final = ?, free_access_pct = ? WHERE id = ?')
          .run(mode, poolDocs, onLoanInPool, excusedDocs, scannedInPool, pctNow, sessionId);
        logAudit('Инвентаризация', (mode === 'full' ? 'пълна' : 'представителна') +
          /* Числата в следата са в БИБЛИОТЕЧНИ ДОКУМЕНТИ, както в протокола.
             Когато инвентарните номера са по-малко (стар неразделен запис), се
             казва и това — иначе следата и таблицата в протокола изглеждат като
             две различни проверки. */
          ' — проверени ' + scannedInPool + ', липсващи ' + missingDocs +
          (missingDocs !== missing.length ? ' (под ' + missing.length + ' инвентарни номера)' : '') +
          ' от ' + poolDocs + ' библиотечни документа' +
          (outOfScope ? ', ' + outOfScope + ' сканирани излязоха от обхвата по време на проверката' : '') +
          (excused.length ? ', ' + excusedDocs + (excusedDocs === 1 ? ' документ за реставрация (не се проверява на място)'
            : ' документа за реставрация (не се проверяват на място)') : '') +
          /* Изгубените от ползватели се назовават ОТДЕЛНО и в следата: дневникът
             е мястото, от което библиотекарката на другия ден вижда защо
             липсите в протокола са по-малко от несканираните. */
          (lostBefore.length ? ', ' + lostDocs + (lostDocs === 1
            ? ' документ, изгубен от ползвател преди проверката (чл. 30, т. 5 — не е липса по чл. 40)'
            : ' документа, изгубени от ползватели преди проверката (чл. 30, т. 5 — не са липси по чл. 40)') : ''));
        const s2 = { free_access_pct: pctNow };
        return {
          mode, scanned: scannedInPool, missing: missingDocs, missingRows: missing.length,
          pool: poolDocs, poolRows: pool.length, outOfScope,
          unchecked: docs(unchecked) + partlyLoaned.reduce((n, b) => n + restOf.get(b.id), 0),
          onLoan: onLoanInPool, atBinder: excusedDocs,
          /* Изгубените преди проверката се връщат със собствено число (v2.4.65),
             за да ги покаже прозорецът след приключването отделно от липсите —
             те не се отчисляват с един и същ акт и не се сравняват с чл. 41. */
          lostBefore: lostDocs, lostBeforeRows: lostBefore.length,
          allowedLoss: naturalLoss(poolDocs, s2.free_access_pct)
        };
      });
      return tx.immediate();
    })
  );
};
