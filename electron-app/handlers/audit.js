// Одитна следа — извадени от main.js в отделен модул (Фаза 4, стъпка 28).
// Единствен read-only справочен handler. Зависи само от getDb, run.
module.exports = function registerAuditHandlers(ipcMain, deps) {
  const { getDb, run } = deps;

  /* ВПИСВАНЕ ОТ ТОЗИ МОДУЛ (v2.4.65, кръг 42, Б21).
     main.js регистрира този модул само с { getDb, run } (main.js:2140) и е
     забранен за промяна в този кръг, тоест `logAudit` тук го няма. Затова редът
     се пише със същото изявление, с което го пише и самият logAudit
     (main.js:1775–1778) — същите колони, същият ред. Ако някой ден main.js
     подаде logAudit, той се ползва и тази реализация отпада от само себе си.
     Колоната `user`: CURRENT_USER живее в main.js и не стига дотук, затова се
     взема последният записан служител в следата — той е този, който работи в
     момента. По-добре вероятно вярно име, отколкото празно „кой“ на ред, чийто
     единствен смисъл е да каже кой е изнесъл личните данни. (Нужната промяна в
     чужд файл — `logAudit` и `getCurrentUser` в зависимостите на този модул —
     е докладвана, не направена.) */
  function note(action, detail) {
    if (typeof deps.logAudit === 'function') return deps.logAudit(action, detail);
    const db = getDb();
    let who = '';
    try {
      const last = db.prepare("SELECT user FROM audit_log WHERE COALESCE(user, '') != '' ORDER BY id DESC LIMIT 1").get();
      who = (last && last.user) || '';
    } catch (e) {
      who = ''; // празна колона „кой“ е по-добра от липсващ ред
    }
    db.prepare('INSERT INTO audit_log (user, action, detail, diff) VALUES (?, ?, ?, NULL)')
      .run(who, action, detail);
  }

  /* Екранът е ограничен до 500 реда (и го казва); ИЗНОСЪТ — не (одит v2.4.25).
     Дотук CSV-то минаваше през същия LIMIT 500 и файлът, който проверяващият
     получава, съдържаше последните 500 от 12 000 записа, без нищо в него да го
     казва. Износът вика с { all: true }. */
  function listAudit(query, all) {
    const db = getDb();
    const limit = all ? '' : 'LIMIT 500';
    if (query && String(query).trim()) {
      const q = `%${String(query).trim()}%`;
      return db.prepare(`
        SELECT * FROM audit_log WHERE user LIKE ? OR action LIKE ? OR detail LIKE ?
        ORDER BY id DESC ${limit}
      `).all(q, q, q);
    }
    return db.prepare(`SELECT * FROM audit_log ORDER BY id DESC ${limit}`).all();
  }
  ipcMain.handle('audit:list', (e, query) => run(() => listAudit(query, false)));
  /* ИЗНОСЪТ НА СЛЕДАТА СЕ ВПИСВА В САМАТА СЛЕДА (v2.4.65, кръг 42, Б21)
     ==========================================================================
     (а) КАКВО СТАВАШЕ ДОТУК. `audit:export` беше ЕДИНСТВЕНОТО извеждане на
     данни навън в цялата програма без ред в следата. Всички останали го правят
     и го казват с думи: „Всяко друго извеждане на данни навън се вписва в
     одитната следа; това единствено не се вписваше“ стои дословно в
     handlers/catalog.js:700–702 над `catalog:exportCsv`. Тоест правилото е
     изписано в проекта, а мястото, за което важи най-силно, беше изключението.
     (б) ЗАЩО Е ГРЕШНО. Одитната следа е регистърът на ВСИЧКИ действия: кой
     служител какво е вписал, поправил и изтрил, с имената на читателите и с
     „преди/след“ на телефони и адреси в `diff`. Изнесена в CSV, тя е най-пълният
     файл с лични данни, който програмата пуска навън наведнъж — по-пълен от
     самия регистър на читателите. При проверка по ОРЗД въпросът е точно „кой и
     кога е изнесъл тези данни“, а отговорът липсваше именно за този файл.
     (в) ЗАЩО ТОЧНО ТАКА. Вписва се СЛЕД като редовете са прочетени — за да
     може броят в реда да е истинският брой изнесени записи, а не намерение — и
     назовава търсенето, ако е имало: „последните 500 от 12 000“ и „всички 12 000“
     са различни файлове и следата трябва да ги различава. Самият ред НЕ влиза
     в изнесения файл (изнася се прочетеното преди него) — така износът не
     документира сам себе си като свое съдържание. */
  ipcMain.handle('audit:export', (e, query) =>
    run(() => {
      const rows = listAudit(query, true);
      const q = String(query || '').trim();
      note('Извеждане на одитната следа', rows.length + ' записа изведени във файл'
        + (q ? ' (търсене „' + q + '“ — изнесени са само съвпадащите редове)' : ' (цялата следа, без филтър)')
        + '. Файлът съдържа имената на читателите и полето „преди/след“ на редакциите '
        + '(телефони, адреси, имейли) — пазете го като лични данни.');
      return rows;
    })
  );
};
