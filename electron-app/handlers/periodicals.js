  /* КАРДЕКСЪТ СЕ ОТВАРЯ ПО ГОДИНА (одит v2.4.61, находка 6).
     =====================================================================
     ДОТУК periodicals:get връщаше ВСИЧКИ броеве на изданието наведнъж, а
     прозорецът ги чертаеше до един — в кутия с превъртане 240 px, и наново след
     ВСЯКО „Добави брой“ и всяко „×“. За ежедневник това са 300 реда след първата
     година, 900 след третата, 3000 след десетата: всяко вписване на днешния
     вестник пречертава цялата история на изданието. Измерено в сценария:
     302 реда се чертаят за секунди, но растежът е линеен и няма таван.
     По-лошото е работното: за да се намери „бр. 117“, няма нито страници, нито
     филтър, нито търсене — само превъртане.
     ЗАЩО ИМЕННО ПО ГОДИНА: кардексът на хартия Е по година (един картон на
     година), комплектът се подвързва по година, и точно година се пита при
     всяка проверка („има ли пълен комплект за 2025 г.“). Годината е и единственият
     разрез, който не изисква от библиотекаря да знае нищо предварително.
     По подразбиране се отваря ТЕКУЩАТА година — в нея се работи всеки ден. Ако
     в нея още няма нито един брой, а по-стари има (издание, чийто абонамент е
     прекратен), се отваря последната година с броеве: празен кардекс при налична
     история изглежда като изгубени данни.
     `issue_total`/`issue_years` се връщат винаги, за да може прозорецът да каже
     „показани N от M“ — числото М е това, което дотук се чертаеше. */
  const YEAR_ALL = 'всички';
  const issueYearExpr = "COALESCE(NULLIF(substr(i.date, 1, 4), ''), '—')";
  function resolveIssueYear(db, id, asked) {
    const years = db.prepare(`SELECT ${issueYearExpr} AS year, COUNT(*) AS n
      FROM periodical_issues i WHERE i.periodical_id = ? GROUP BY 1 ORDER BY 1 DESC`).all(id);
    const want = asked == null ? '' : String(asked).trim();
    if (want === YEAR_ALL) return { year: YEAR_ALL, years };
    if (/^\d{4}$/.test(want) || (want === '—' && years.some(y => y.year === '—'))) return { year: want, years };
    const cur = String(yearOf());
    if (!years.length || years.some(y => y.year === cur)) return { year: cur, years };
    /* Издание без броеве в текущата година се отваря на последната, в която има —
       празен картон при налична история изглежда като изгубени данни. Броевете без
       дата (внесени от стар файл) стоят в кошчето „—“ и НЕ стават подразбиращ се
       изглед: то е за поправяне, не за ежедневна работа. */
    const dated = years.filter(y => /^\d{4}$/.test(y.year));
    return { year: (dated[0] || years[0]).year, years };
  }
