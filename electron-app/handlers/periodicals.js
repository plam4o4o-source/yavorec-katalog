const PER_FN_READY = new WeakSet();
function ensurePeriodicalFunctions(db) {
  if (PER_FN_READY.has(db)) return db;
  db.function('bglower', (s) => (s == null ? null : String(s).toLowerCase()));
  db.function('bgsqueeze', (s) => (s == null ? null : String(s).trim().replace(/\s+/g, ' ')));
  PER_FN_READY.add(db);
  return db;
}
/* Ключът на заглавието — едно и също изражение и от двете страни на сравнението:
   в JavaScript за входа, през SQL функциите за вече записаното. */
function titleKey(s) {
  return String(s == null ? '' : s).trim().replace(/\s+/g, ' ').toLowerCase();
}

