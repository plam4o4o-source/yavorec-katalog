  /* Одит v2.4.29: better-sqlite3 подава всяко JS число като REAL, а SQLite го
     записва в TEXT колона като „2002.0“ — година „2002.0“, страници „250.0“.
     Формата праща низове, но вносът от стар каталог, мобилният път и бъдещи
     обаждания не са длъжни; текстовите полета се привеждат към низ тук, веднъж. */
  const BOOK_TEXT_FIELDS = new Set(['inv_number', 'category_id', 'acquisition_id', 'price'].reduce(
    (set, f) => { set.delete(f); return set; }, new Set(BOOK_FIELDS)));
  function bookPayload(b, prev) {
    const out = {};
    BOOK_FIELDS.forEach(f => {
      let v = b[f] === undefined || b[f] === '' ? null : b[f];
      if (v != null && BOOK_TEXT_FIELDS.has(f) && typeof v === 'number') v = String(v);
      if (f === 'barcode' && v != null) v = String(v).trim() || null; // „BC-1 “ ≠ „BC-1“ за четеца
      out[f] = v;
    });
    /* ИНВЕНТАРНИЯТ НОМЕР МИНАВА ПРЕЗ СЪЩАТА ВРАТА КАТО ВСИЧКИ ДРУГИ НОМЕРА В
       РЕГИСТРИТЕ (v2.4.61).
       Дотук тук стоеше гол `parseInt(out.inv_number, 10)` — точно това, което
       parseRegisterNo() в security-utils.js съществува да замести навсякъде
       (партида, акт, протокол по чл. 40, заявка за МЗС го ползват отдавна).
       Доказано изпълнимо през формата и през всеки друг път:
         • инв. № 0      — приемаше се; поредицата на инвентарната книга започва
                           от 1, а 0 е и стойността, до която CAST('' AS INTEGER)
                           свежда празно сканиране (виж normalizeScanCode) —
                           тоест ред с № 0 се намира от празен скан;
         • инв. № −4     — приемаше се и се печаташе като „инв. № -4“;
         • инв. № „12.7“ — parseInt го отрязваше до 12 БЕЗ ДУМА: документът се
                           вписваше под чужд номер, а ако 12 вече е зает, отказът
                           говореше за номер, който библиотекарят не е въвеждал.
       Инвентарният номер е реквизит по чл. 16, ал. 2 и мястото на документа в
       поредицата; той е или цяло положително число, или отказ, който казва защо.
       `allowEmpty` е вярно: празно поле остава NULL (стар внесен ред без номер,
       черновата на периодиката), както и досега — проверката е за въведена, но
       негодна стойност. */
    if (out.inv_number != null) out.inv_number = parseRegisterNo(out.inv_number, 'Инвентарният номер', true);
    if (out.category_id != null) out.category_id = parseInt(out.category_id, 10);
    if (out.acquisition_id != null) out.acquisition_id = parseInt(out.acquisition_id, 10);
    out.price = parseBookPrice(b.price);   // виж parseBookPrice по-горе
    /* Одит v2.3.1 №9(b): досега липсваща/празна стойност за status ставаше винаги
       'наличен' — вярно за НОВ запис (разумна стойност по подразбиране), но при
       РЕДАКЦИЯ на съществуващ ред мълчаливо превръщаше NULL статус (стари данни,
       все още непрегледани от библиотекаря) в 'наличен' — включително в публичния
       онлайн каталог (main.js: publicBookFields), макар NULL да не значи „наличен“
       никъде в програмата. Редакция без изрична нова стойност вече пази текущия
       статус на реда какъвто и да е — NULL или непозната стара стойност включително;
       'наличен' по подразбиране остава само когато записът реално се създава (prev
       липсва).*/
    out.status = b.status || (prev ? prev.status : 'наличен');
    /* ДАТАТА НА ВПИСВАНЕ СЕ ПРОВЕРЯВА (v2.4.57).
       Дотук тук стоеше само `b.register_date || today()` — в целия този файл
       нямаше нито едно повикване на isValidIsoDate, докато актът за отчисляване,
       протоколът по чл. 40, МЗС и заемането всички го правят изрично. Тоест
       най-често въвежданият път в цялата програма беше единственият непроверен.

       Доказано изпълнимо: books:create с register_date 'НЕВАЛИДНА-99-99' минаваше,
       редът влизаше в базата, и после документът пропадаше през ВСИЧКИТЕ ТРИ
       мрежи наведнъж — не е <= '2026-12-31' (кирилското „Н“ сортира след
       цифрите), substr(...,1,4) не е година, и броячът „без дата на вписване“
       търсеше само IS NULL или празно. Измерено при три документа (10 лв., 99 лв.
       със счупена дата, 50 лв.):

         КДБФ наличност 31.12  : 2 документа, 60 лв.   ← 99-те лева ги няма
         КДБФ постъпили        : 2 документа, 60 лв.   ← и тук ги няма
         КДБФ „без дата“       : 0                      ← и тук ги няма
         Табло                 : 3 документа            ← а тук ги има

       Документ за 99 лв. е във фонда, брои се на таблото, може да се заема — и
       НЕ СЪЩЕСТВУВА в официалния регистър по Наредба № 3. Разликата е невидима:
       няма екран, на който да се види, че нещо липсва.

       Датата на вписване е реквизит по чл. 16, ал. 2 и мястото на документа във
       времето — тя решава в коя година се брои постъплението. Невалидна дата
       не е „по-добра от нищо“: тя е по-лоша от липсваща, защото липсващата поне
       се брои от предупреждението за недатирани документи. */
    if (b.register_date && !isValidIsoDate(b.register_date)) {
      throw new Error('Датата на вписване „' + b.register_date + '“ не е валидна дата. '
        + 'Тя решава в коя година се брои постъплението в Книгата за движение на фонда — '
        + 'въведете я като ден, месец и година, или я оставете празна.');
    }
    out.register_date = b.register_date || today();
    out.cn_sort = out.call_number ? cnSortKey(out.call_number) : null;
    out.status_date = !prev ? today()
      : (prev.status !== out.status ? today() : (prev.status_date || null));
    return out;
  }

  // sort: 'title' (по подразбиране), 'cn' (по сигнатура — cn_sort нарежда „Ч-9" преди
  // „Ч-84", виж cnSortKey) или 'inv' (по инвентарен номер). Изборът е от фиксиран
  // списък тук, никога суров SQL от интерфейса.
  // `, b.id` накрая (v2.4.31): порциите с LIMIT/OFFSET изискват устойчив ред и при равни заглавия.
  const BOOK_ORDERS = { title: 'b.title, b.id', cn: "b.cn_sort IS NULL, b.cn_sort, b.title, b.id", inv: 'b.inv_number, b.id' };
  /* Условието за търсене, общо за пълния списък и за прозореца (v2.4.31). Връща
     { where, params } — празно търсене = без условие.
     Заглавие/подзаглавие/автор минават през FTS5 (unicode61) — сгъва регистъра
     и по кирилица ("белият" вече намира "Белият"), без пълно сканиране на
     таблицата. Баркод/ISBN/инв. № остават на LIKE — ASCII цифри, за които
     потребителите очакват "съдържа навсякъде", а не само префикс. */
  function booksSearchWhere(query) {
    if (!query || !query.trim()) return { where: '', params: [] };
    const q = `%${query.trim()}%`;
    return {
      where: `(b.id IN (SELECT rowid FROM books_fts WHERE books_fts MATCH ?)
             OR b.isbn LIKE ? OR b.barcode LIKE ? OR CAST(b.inv_number AS TEXT) LIKE ?)`,
      params: [ftsQuery(query), q, q, q]
    };
  }
  /* books:list(query, sort) — пълният резултат като масив (както досега:
     износите и старите изгледи; етикетите вече НЕ минават оттук).
     books:list(query, sort, page) — ПРОЗОРЕЦ (v2.4.31, производителност): при
     15 000 документа пълният списък е 5,5 МБ и ~150 ms в SQLite при ВСЯКО отваряне
     на „Книги“ и всяко търсене, а на екрана стоят 300 реда. page = { offset, limit,
     dept, cat } връща { rows, total, depts } — само порцията, общия брой за брояча
     и отделите, срещани в резултата (за падащия филтър). page.idsOnly връща
     { ids } — всички идентификатори на резултата за „Избери всички“.
     books:list(query, sort, { labels: true, from, to }) — ЕТИКЕТИ (v2.4.64):
     МАСИВ с шестте полета от LABEL_SELECT за инвентарните номера между `from` и
     `to` (празно = без граница, тоест целият действащ фонд), подреден по
     инвентарен номер. `query` и `sort` се пренебрегват съзнателно: етикетът се
     печата по инвентарен номер — по този ред се реже и лепи листът — и никой от
     четирите бутона за етикети не търси. Защо режимът е ТУК, а не отделен канал:
     етикетите открай време искат „същото, което е в списъка, но за диапазон“, а
     един канал за фонда значи и едно място, на което се решава кое е „действащ
     фонд“ (виж labelRows по-горе). */
  ipcMain.handle('books:list', (e, query, sort, page) =>
    run(() => {
      const db = getDb();
      if (page && typeof page === 'object' && page.labels) return labelRows(db, page);
      const order = BOOK_ORDERS[sort] || BOOK_ORDERS.title;
      const { where, params } = booksSearchWhere(query);
      if (!page || typeof page !== 'object') {
        return db.prepare(`${BOOK_LIST_SELECT} ${where ? 'WHERE ' + where : ''} ORDER BY ${order}`).all(...params);
      }
      const conds = where ? [where] : [];
      const p = [...params];
      if (page.dept) { conds.push('COALESCE(b.department, \'\') = ?'); p.push(String(page.dept)); }
      if (page.cat != null && page.cat !== '') { conds.push('b.category_id = ?'); p.push(parseInt(page.cat, 10)); }
      const W = conds.length ? 'WHERE ' + conds.join(' AND ') : '';
      if (page.idsOnly) {
        return { ids: db.prepare(`SELECT b.id FROM books b ${W}`).pluck().all(...p) };
      }
      /* Таванът е 3 000, колкото е и RENDER_MAX_ROWS в src/views/core.js —
         същото число на двете места (v2.4.65, кръг 42, находка В9). Дотук беше
         2 000 и точно това режеше презареждането на разгърнат списък след запис
         на книга: екранът чертаеше 3 000 реда с честния надпис „Показани са
         първите 3 000 от 3 500“, а след първия запис се свиваше на 2 000 БЕЗ
         надпис. Обработчикът и изгледът искат едно и също число; дългото
         обяснение защо точно 3 000 (283 ms и +248 МБ на измерването) стои при
         RENDER_MAX_ROWS и не се преписва тук. */
      const limit = Math.min(Math.max(parseInt(page.limit, 10) || 300, 1), 3000);
      const offset = Math.max(parseInt(page.offset, 10) || 0, 0);
      const rows = db.prepare(`${BOOK_LIST_SELECT} ${W} ORDER BY ${order} LIMIT ? OFFSET ?`).all(...p, limit, offset);
      const total = db.prepare(`SELECT COUNT(*) AS n FROM books b ${W}`).get(...p).n;
      /* Отделите в резултата от търсенето (без филтъра по отдел — иначе менюто се
         свива до избрания). БЕЗ отчислените (v2.4.57): отдел, в който са останали
         само отчислени документи, продължаваше да стои в менюто, а изборът му
         връщаше точно тях. Отчисленият документ пази отдела си нарочно — той е
         част от снимката и от справките за минали години (виж защо не се чисти
         при отчисляване) — но менюто отговаря на въпроса „къде да търся книга“,
         а там отговорът е само фондът. */
      const deptWhere = [where, FUND.fundByStatus].filter(Boolean).join(' AND ');
      const depts = db.prepare(`SELECT DISTINCT b.department FROM books b WHERE ${deptWhere}
        ORDER BY b.department`).pluck().all(...params).filter(Boolean);
      return { rows, total, depts, offset, limit };
    })
  );
  /* `_rev` е отпечатъкът на реда към момента на отварянето (v2.4.56) — формата
     го връща при записа и books:update отказва, ако междувременно друго работно
     място е пипнало същия документ. Виж rowFingerprint в security-utils.js. */
  ipcMain.handle('books:get', (e, id) => run(() => {
    const b = getDb().prepare(`${BOOK_SELECT} WHERE b.id = ?`).get(id);
    if (b) b._rev = rowFingerprint(b, BOOK_FIELDS);
    return b;
  }));
  ipcMain.handle('books:byBarcode', (e, code) =>
    // CAST-ва се ПАРАМЕТЪРЪТ, не колоната — CAST(b.inv_number AS TEXT) = ? би
    // попречил на SQLite да ползва нито idx_books_barcode, нито уникалния индекс
    // на inv_number, и би прибягнал до пълно сканиране на фонда въпреки индекса
    // (потвърдено с EXPLAIN QUERY PLAN: с тази форма планът е MULTI-INDEX OR по
    // двата индекса). normalizeScanCode() (v1.70.1) — виж security-utils.js:
    // баркод четецът е клавиатура, а активна кирилска разредба на Windows
    // превръща букви от Code 39 баркода (напр. B) в кирилски еквивалент (Б).
    // Одит v2.4.24: resolveScannedBook() вместо `OR ... CAST` + .get() — при код,
    // който е баркод на един документ и инвентарен номер на друг, се отказва с
    // ясно съобщение, вместо да се върне произволният (по rowid) от двата.
    run(() => { const c = normalizeScanCode(code); return c ? resolveScannedBook(getDb(), c, BOOK_SELECT) : null; })
  );

  /* ЕДИН ИНВЕНТАРЕН НОМЕР = ЕДИН ЕКЗЕМПЛЯР.
     Това е правилото на инвентарната книга и то важи навсякъде в програмата
     (потвърдено от библиотеката, v2.4.21). Дотук `inventory.quantity` беше
     свободно число, картонът предлагаше поле „Налични бройки“, а наръчникът
     изрично учеше библиотекаря да впише там броя екземпляри — тоест самата
     програма учеше на обратното на правилото, а цял слой аритметика Σ(бройки)
     съществуваше, за да поддържа случай, който не бива да съществува.
     Оттук нататък програмата НЕ създава ред с друга бройка освен 1. Втори
     екземпляр от същото заглавие е ВТОРИ ЗАПИС със свой инвентарен номер
     („+ Още екземпляр“ в картона).
       • create: непосочено → 1;
       • update: непосочено → ЗАПАЗВА текущата стойност. Дотук се нулираше на 1 —
         а картонът вече не праща бройка. Стар неразделен запис (3 екземпляра под
         един номер, внесена стара база), отворен за поправка на правописна
         грешка, би загубил два документа от фонда тихо. Точно това е сплескването,
         което правилото трябва да предотврати, не да причини;
       • стойност > 1 се ОТХВЪРЛЯ с указание, вместо да се сплесква.
     Вече съществуващите редове с бройка ≠ 1 се намират от books:multiCopyRecords
     и се оправят от books:splitCopies / books:setLendable — там сборът не се
     променя. */
  function normalizeQuantity(q, keep) {
    if (q === undefined || q === null || q === '') return keep === undefined ? 1 : keep;
    const n = parseInt(q, 10);
    if (!Number.isFinite(n) || n < 0) throw new Error('Бройката трябва да е 1 — един инвентарен номер отговаря на един екземпляр.');
    /* Одит v2.4.22 (преглед на поправката от v2.4.21): дотук минаваше и n=0 — точно
       стойността, която books:setLendable и „Проверка на данните“ по-долу
       съществуват да откриват и оправят, защото прави документа невидим за всеки
       сбор на фонда. Функцията, която трябва да е единствената врата към
       inventory.quantity от създаване/редакция на картон, имаше дупка за точно тази
       стойност. 0 се записва само от целенасочените инструменти (books:setLendable
       я връща на 1; books:splitCopies пише 1 директно за всеки нов ред) — никога
       през това поле, независимо какво е подадено. */
    if (n === 0) {
      throw new Error('Бройка 0 прави документа невидим за фонда. Ако записът е стар и наистина е с бройка 0, '
        + 'поправете го от „Настройки“ → „Проверка на данните“, не от картона.');
    }
    if (n > 1) {
      throw new Error('Един инвентарен номер отговаря на ЕДИН екземпляр. За втори екземпляр от същото '
        + 'заглавие използвайте „+ Още екземпляр“ в картона — той създава нов запис със следващия '
        + 'инвентарен номер, както изисква инвентарната книга.');
    }
    return n;
  }

  /* ЗАЕТИЯТ ИНВЕНТАРЕН НОМЕР КАЗВА КАКВО ДА СЕ НАПРАВИ (v2.4.57).
     Формата се предпопълва със settings.next_inv_number при ОТВАРЯНЕ, а номерът
     се заема чак при записа. При два компютъра към една мрежова база (изрично
     поддържан режим) и двамата отварят „Нов документ“ с № 512 и вторият запис
     пада върху UNIQUE индекса на books.inv_number. Дотук библиотекарката
     получаваше общия превод на SQLite грешката — „Този инвентарен номер вече е
     зает от друг документ.“ (main.js, friendlyDbError) — вярно изречение, което
     обаче не казва НИТО защо се е случило, НИТО какво да се направи; типичната
     реакция е да се въведе „свободен“ номер на ръка, което пробива дупка в
     поредицата (виж следващата бележка). Актът за отчисляване, протоколът по
     чл. 40, МЗС и партидата в КДБФ всички вече обясняват точно този случай с
     едно и също изречение; инвентарният номер — най-често заеманият номер в
     цялата програма — беше единственият без него.
     Проверката е ВЪТРЕ в транзакцията, пусната с .immediate() (правото на запис
     се взима преди четенето), затова между нея и INSERT-а никой не може да
     вмъкне същия номер; UNIQUE индексът остава последната преграда.

     `selfId` (v2.4.61) е редът, който САМ държи номера при редакция — той не се
     брои за зает. Дотук тази проверка съществуваше само за създаването, а при
     редакция единствената преграда беше UNIQUE индексът, чийто превод
     (main.js, friendlyDbError) гласи „Този инвентарен номер вече е зает от друг
     документ.“ — без да каже КОЙ е другият документ. А точно при редакция това
     е единственото, което върши работа: библиотекарката сверява два картона и
     решава кой от двата е сгрешен. Затова при редакция съобщението назовава
     държателя и съветва друго — не „затворете формата“ (номерът в нея не е
     предложен от програмата, а въведен от човека), а изберете свободен номер. */
  function assertInvNumberFree(db, invNumber, selfId) {
    if (invNumber == null) return;
    const other = db.prepare('SELECT id, title FROM books WHERE inv_number = ? AND id != ? LIMIT 1')
      .get(invNumber, selfId == null ? -1 : selfId);
    if (other) {
      throw new Error('Инв. № ' + invNumber + ' вече е зает от „' + (other.title || 'без заглавие') + '“ — '
        + (selfId == null
          ? 'най-вероятно е създаден от друго работно място към същата база. '
            + 'Затворете и отворете формата отново, за да получите следващия свободен номер.'
          : 'един инвентарен номер отговаря на един екземпляр (чл. 16, ал. 2). Проверете кой от двата '
            + 'картона носи сгрешения номер и въведете свободен номер.'));
    }
  }
  /* ПРЕСКОЧЕНИЯТ НОМЕР ВЕЧЕ ОСТАВЯ СЛЕДА (v2.4.57).
     Дотук ръчно въведен инвентарен номер, по-голям от следващия по ред, просто
     избутваше брояча напред: `if (inv >= next) next = inv + 1` — без дума, без
     ред в дневника, без нищо на екрана. Проверено емпирично: при next_inv № 3
     създаването на документ с № 5000 оставя next_inv 5001 и 4997 неизползвани
     номера, за които в програмата няма НИКАКВА следа.
     Защо това е грешно ЗА БИБЛИОТЕКАТА: инвентарната книга е поредица и
     проверката по чл. 17, ал. 2 иска отговор за ВСЕКИ номер в нея. Самата
     програма вече знае това — books:delete отказва изтриване именно с довода,
     че „инвентарен № N остава празно място в поредицата и при проверка няма с
     какво да се обясни“. Същият довод важи дословно и при създаването, само че
     там дупката е не един номер, а хиляди — и се пробива по-лесно, отколкото се
     трие документ.
     Защо поправката е точно такава: номерът НЕ се отказва. Скокът е законен и
     обичаен — библиотеката минава на нова хилядна поредица, продължава номерация
     от стара книга, дарение получава отделен блок. Отказът би спрял редовна
     работа. Отказва се само МЪЛЧАНИЕТО: задължителен ред в одитната следа с
     броя прескочени номера (за да има какво да се каже при проверка) и
     предупреждение обратно към прозореца, за да го види човекът, който още е
     пред формата и може да се поправи. */
  function invGapNotice(previousNext, invNumber) {
    const from = parseInt(previousNext, 10);
    if (!Number.isFinite(from) || from <= 0 || invNumber == null || invNumber <= from) return null;
    const skipped = invNumber - from;
    return {
      inv_number: invNumber, from, to: invNumber - 1, skipped,
      message: 'Инв. № ' + invNumber + ' е въведен на ръка, а по ред следваше № ' + from + '. '
        + (skipped === 1
          ? 'Номер ' + from + ' остава празен в инвентарната книга'
          : 'Номерата от ' + from + ' до ' + (invNumber - 1) + ' (' + skipped + ' на брой) остават празни в инвентарната книга')
        + ' и при проверка по чл. 17, ал. 2 няма с какво да се обяснят. '
        + 'Ако това е нарочно (нова поредица, продължение на стара книга), няма какво да се прави — '
        + 'записът вече е отбелязан в дневника. Ако номерът е сгрешен, поправете го сега, докато документът е сам в поредицата.'
    };
  }
