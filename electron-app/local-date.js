'use strict';
/* „Днес“ по часовника на компютъра, не по UTC (v2.4.67).
   ------------------------------------------------------------------------
   Дотук „днес“ навсякъде беше `new Date().toISOString().slice(0, 10)` — това е
   датата в ГРИНУИЧ. В България (UTC+2 зиме, UTC+3 лете) между 00:00 и 02:00/03:00
   тя е ВЧЕРАШНАТА: заемане след полунощ се записваше с вчерашна дата и срок с
   ден по-кратък, книга с падеж „вчера“ още не беше просрочена, а годишният отчет
   в новогодишната нощ пишеше старата година. Същото беше и с `date('now')` в
   SQLite — затова там вече е `date('now', 'localtime')`.

   Смятането С ДАТИ (добави N дни, ден от седмицата, ISO седмица) остава в UTC
   нарочно — там „T00:00:00Z“ пази от смяната на часа. Тук е само въпросът
   „коя дата е СЕГА“. */
function localDate(d) {
  const t = d || new Date();
  const pad = (n) => String(n).padStart(2, '0');
  return t.getFullYear() + '-' + pad(t.getMonth() + 1) + '-' + pad(t.getDate());
}

module.exports = { localDate };
