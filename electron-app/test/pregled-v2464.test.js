'use strict';
/* ============================================================================
   ПРЕГЛЕД НА КРЪГА v2.4.64 — четирите поправени находки.
   ============================================================================
   Кръгът за v2.4.64 внесе три полезни промени, всяка от които остави по един
   ръб. Тестовете тук заковават поправките, а не намеренията:

     1) „before-reset-…“ се ПРЕКРИПТИРА при смяна на паролата. Копието отпреди
        „Започване на чисто“ е единственото, което още съдържа старата
        библиотека — базата след изтриването е празна. Оставено извън филтъра
        на reencryptOldBackups(), смяната на паролата (най-честият повод:
        напуснал служител) го заключваше ЗАВИНАГИ. Същият пропуск вече беше
        поправян веднъж, за „before-restore-…“ (одит v2.4.24).
     2) търсенето в кардекса вижда ВСИЧКИ броеве, а не само нарисуваната порция;
     3) празният печат на инвентарната книга казва КОИ ограничения действат —
        диалогът от v2.4.64 сам попълва текущата година, тоест ограничение,
        което библиотекарката не е задавала;
     4) надписът за некриптираните предпазни копия назовава и двата префикса,
        защото числото над него брои и двата.

   Всеки тест е проверен с връщане на поправката. */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');

const APP_DIR = path.join(__dirname, '..');
const read = (...p) => fs.readFileSync(path.join(APP_DIR, ...p), 'utf8');

/* ------------------------------------------------------------------ 1 ---- */
test('прекриптирането при смяна на паролата обхваща и копието отпреди изтриването', () => {
  const src = read('handlers', 'backup.js');
  const at = src.indexOf('function reencryptOldBackups');
  assert.notEqual(at, -1, 'липсва reencryptOldBackups');
  /* Отрязва се до края на функцията по БАЛАНСИРАНИ скоби, а не по брой знаци:
     филтърът може да се премести няколко реда по-надолу, без това да значи, че
     е изчезнал. */
  let i = src.indexOf('{', at), depth = 0, end = src.length;
  for (let j = i; j < src.length; j++) {
    if (src[j] === '{') depth++;
    else if (src[j] === '}') { depth--; if (!depth) { end = j + 1; break; } }
  }
  const body = src.slice(at, end);

  for (const [re, what] of [
    [/\^auto-/, 'дневните копия'],
    [/\^before-restore-/, 'копията отпреди възстановяване'],
    [/\^before-reset-/, 'копието отпреди изтриването на всички данни']
  ]) {
    assert.match(body, re, 'reencryptOldBackups трябва да обхваща ' + what
      + ' — иначе смяната на паролата ги заключва завинаги със старата');
  }

  /* И името, което reset.js наистина дава на файла, трябва да минава през
     филтъра — иначе двата файла биха се разминали при преименуване. */
  const reset = read('handlers', 'reset.js');
  assert.match(reset, /'before-reset-' \+ backupTimestamp\(\)/,
    'handlers/reset.js трябва да пише точно този префикс');
  const sample = 'before-reset-2026-09-22-11-30-00.invbak';
  const filters = [/^auto-\d{4}-\d{2}-\d{2}\.invbak$/, /^before-restore-.+\.invbak$/, /^before-reset-.+\.invbak$/];
  assert.ok(filters.some(r => r.test(sample)),
    'истинското име на копието отпреди изтриването трябва да съвпада с някой от филтрите');
});

/* ------------------------------------------------------------------ 2 ---- */
/* ПРОМЕНЕНА ПОПРАВКА (v2.4.65, находка А11).
   Тестът дотук заковаваше решението от v2.4.64: търсачката ДОРИСУВАШЕ целия
   списък и чак после скриваше несъвпадащите редове с display:none. Това решение
   обаче се чупи над 3 000 броя — общият таван RENDER_MAX_ROWS в core.js не
   позволява повече редове в тялото и броят отвъд третохилядния просто няма как
   да се появи, тоест търсенето по него пак отговаря „0 намерени“ (ежедневник от
   около 2015 г. насам). Затова филтърът вече слиза върху МАСИВА с броеве и се
   рисуват само съвпаденията — таванът се прилага върху резултата от търсенето,
   а не върху самото търсене. Тестът пази същото нещо (търсачката да вижда
   всички броеве, не само нарисуваните), но през новото решение. */
test('търсенето в кардекса пресява данните, а не нарисуваните редове', () => {
  const src = read('src', 'views', 'periodicals.js');
  const fn = (name) => {
    const at = src.indexOf('function ' + name);
    assert.notEqual(at, -1, 'липсва ' + name);
    let depth = 0, end = src.length;
    for (let j = src.indexOf('{', at); j < src.length; j++) {
      if (src[j] === '{') depth++;
      else if (src[j] === '}') { depth--; if (!depth) { end = j + 1; break; } }
    }
    return src.slice(at, end);
  };

  const matches = fn('perIssueMatches');
  assert.match(matches, /_PER_KARDEX/,
    'пресяването трябва да чете броевете от данните на прозореца, не от тялото на таблицата');
  assert.match(matches, /\.filter\(/, 'пресява се самият масив с броеве');

  /* И най-важното: нарисуваните редове НЕ участват в търсенето — нито се четат,
     нито се скриват. Точно това е разликата, заради която таванът от 3 000 реда
     вече не може да скрие вписан брой от търсачката. */
  const filter = fn('filterIssueRows');
  assert.equal(filter.indexOf("querySelectorAll('tr')"), -1,
    'филтърът не бива да чете редовете от тялото — те са само първите 3 000');
  assert.equal(filter.indexOf('style.display'), -1,
    'несъвпадащите редове не се скриват, а изобщо не се чертаят');
  assert.match(filter, /paintPerIssues\(false\)/,
    'всяка смяна на търсенето е пълен рендер — иначе новият резултат се долепя към стария');

  /* Таванът остава ЕДИН и общ (core.js) — този екран не си прави свой. */
  assert.ok(!/const\s+\w*_MAX_ROWS\s*=/.test(src), 'таванът не се преоткрива тук — той е един, в core.js');
});

/* ------------------------------------------------------------------ 3 ---- */
test('празният печат на инвентарната книга изброява действащите ограничения', () => {
  const src = read('src', 'views', 'inv-book.js');
  const at = src.indexOf('if (sel.limited && !rows.length)');
  assert.notEqual(at, -1, 'липсва проверката за празен диапазон');
  const msg = src.slice(at, at + 900);
  assert.match(msg, /sel\.label/,
    'съобщението трябва да назове ВСИЧКИ действащи ограничения, а не само да прати човека '
    + 'да проверява числата, които е написал сам');
  assert.match(msg, /дат/i,
    'диалогът сам попълва текущата година, затова съобщението трябва да насочи и към датите');

  /* И самото предварително попълване остава — то е нарочно (печат на цялата
     книга е 2,7 s замръзнал прозорец), но точно затова съобщението трябва да
     го казва. */
  assert.match(src, /'Вписани от дата', 'dateFrom', \{ type: 'date', val: curYear/,
    'диалогът по подразбиране ограничава до текущата година');
});

/* ------------------------------------------------------------------ 4 ---- */
test('надписът за некриптираните предпазни копия назовава и двата префикса', () => {
  const backup = read('handlers', 'backup.js');
  /* Какво БРОИ програмата. */
  assert.match(backup, /plainRestoreCount = names\.filter\(f => f\.startsWith\('before-restore-'\) \|\| f\.startsWith\('before-reset-'\)\)/,
    'броячът обхваща и двата префикса');

  /* Какво ПИШЕ на екрана — трябва да е същото, иначе библиотекарката брои в
     папката по-малко файлове от обявеното и решава, че екранът лъже. */
  const settings = read('src', 'views', 'settings.js');
  const at = settings.indexOf('const restoreNote');
  assert.notEqual(at, -1, 'липсва надписът за предпазните копия');
  const note = settings.slice(at, at + 1200);
  /* Търси се ВИДИМИЯТ надпис (<code>…</code> в шаблона), а не просто низът
     някъде наблизо: първата редакция на този тест минаваше заради обяснителния
     коментар над самия шаблон — тоест твърдеше, че екранът казва нещо, което
     екранът не казваше. Хванато с връщане на поправката. */
  assert.match(note, /<code>before-restore-…<\/code>/,
    'надписът трябва да назове копията отпреди възстановяване');
  assert.match(note, /<code>before-reset-…<\/code>/,
    'надписът трябва да назове и копието отпреди изтриването — числото над него го брои');

  /* И бележката в reset.js вече не бива да твърди обратното. */
  const reset = read('handlers', 'reset.js');
  assert.ok(!/няма да се появи в\s*\n?\s*броячите на екрана/.test(reset),
    'бележката в handlers/reset.js твърдеше, че копието не влиза в броячите — то влиза');
});
