const { execFileSync } = require('child_process');
const fx = require('./helpers/audit-fixtures');

const APP_DIR = fx.APP_DIR;
test.after(fx.cleanupTmpDirs);

function startAgainstDb(userVersion, mode) {
  const out = execFileSync(process.execPath,
    [path.join(__dirname, 'helpers', 'newer-schema-worker.js'), String(userVersion)].concat(mode ? [mode] : []),
    { encoding: 'utf8', timeout: 60000 });
  return JSON.parse(out.trim().split('\n').filter(l => l.startsWith('{')).pop());
}

/* ==================================================================
   1. ПАЗАЧЪТ НАПРЕД — и при надпревара по време на самото стартиране
   ================================================================== */
test('база, обновена ПО ВРЕМЕ на стартирането, пак се отказва', () => {
  /* Режим 'race' на worker-а: базата тръгва с познатата версия (проверката при
     отварянето минава), а докато initDb() тече, втора връзка я вдига до 99 —
     точно каквото прави другото, вече обновено работно място в деня на
     обновяването. Преди тази поправка: exitCode 0, нула диалози, ПЪЛНА работна
     сесия срещу по-новата база — записваща стари формати (напр. sum = 0 като
     „непопълнено“) в схема, която ги чете другояче. */
  const r = startAgainstDb(99, 'race');
  assert.equal(r.exitCode, 1, 'стартирането спира и при късно установено разминаване');
  assert.equal(r.dialogs.length, 1);
  assert.match(r.dialogs[0].title, /по-стар от базата данни/);
  /* За този път твърдението „не е записала нищо“ НЕ ни се полага — сервизната
     част на стартирането вече е минала. Диалогът казва само каквото е вярно. */
  assert.match(r.dialogs[0].content, /докато тази програма стартираше/);
  assert.ok(!/не е записала нищо в нея/.test(r.dialogs[0].content),
    'късният отказ не обещава недокосната база');
  /* v2.4.21: и не обещава „не е записала ваши данни“ — сервизната част ВЕЧЕ е
     записала (работникът го измерва: consentAfter, journalAfter, untouched).
     Първата редакция проверяваше sumAfter === 0, което е вярно и без пазача —
     миграция 11 не може да тръгне при версия 99. */
  assert.ok(!/каквито и да е ваши данни/.test(r.dialogs[0].content), 'обещанието за недокоснати данни е махнато');
  assert.match(r.dialogs[0].content, /Сервизната част на стартирането обаче вече беше минала/,
    'диалогът казва точно какво е станало');
  /* Преглед на поправките (v2.4.23): `untouched === false` беше празно твърдение —
     в режим race собствената втора връзка на работника вдига версията СЛЕД
     контролната сума, тоест файлът е „докоснат“ каквото и да прави програмата.
     Доказателството са двете конкретни следи, които работникът измерва. */
  assert.equal(r.consentAfter, '2020-01-01', 'старият backfill наистина е пренаписал датата на съгласието');
  assert.equal(r.journalAfter, 'wal', 'и журналът наистина е сменен');
  assert.equal(r.sumAfter, 0, 'миграция 11 не е пипнала данните');
});

/* ==================================================================
   2. ДИАЛОГЪТ — казва dbFolder само когато dbFolder съществува
   ================================================================== */
test('при споделена (мрежова) папка диалогът сочи изхода през dbFolder', () => {
  const r = startAgainstDb(99, 'network');
  assert.equal(r.exitCode, 1);
  assert.equal(r.untouched, true, 'и на мрежовата папка базата остава непокътната');
  const c = r.dialogs[0].content;
  assert.match(c, /обща[\s\S]*мрежова папка/);
  assert.match(c, /dbFolder/);
  assert.match(c, /config\.json/);
  assert.match(c, /СОБСТВЕНА база/);
});

test('при чисто локална база диалогът не съчинява мрежова папка', () => {
  /* Дефект в поправката от v2.4.19: абзацът с изхода се печаташе БЕЗУСЛОВНО —
     включително „базата е обща (мрежова папка)“ и „изтрийте реда dbFolder“ за
     инсталация, при която ред dbFolder в config.json изобщо няма (пуснат
     по-стар инсталатор върху локално мигрирани данни). Невярна инструкция върху
     екрана, чийто смисъл е точното упътване. */
  const r = startAgainstDb(99);
  assert.equal(r.exitCode, 1);
  const c = r.dialogs[0].content;
  assert.ok(!/dbFolder/.test(c), 'няма съвет за ред, който не съществува');
  assert.ok(!/мрежова папка/.test(c), 'няма твърдение, че базата е обща');
  assert.match(c, /не е записала нищо в нея/, 'верните твърдения остават');
  assert.match(c, /Обновете InvLib/);
});

/* ==================================================================
   3. „STALE“ — без обещание, което отключването не винаги изпълнява
   ================================================================== */
test('повредена партида при ВЕРЕН ключ е „unreadable“, не „stale“ — и полетата остават за въвеждане', () => {
  /* v2.4.20 закова обратното: „stale настъпва и при повредена партида, където
     отключването отказва“ — и оттам картонът носеше указание, което не може да се
     изпълни (формата заключва полетата при stale). Причината беше партидната
     евристика: цялата партида е нечетима ⇒ stale, без да се пита ДАЛИ ключът
     изобщо е сменен. v2.4.21: решението е по проверителя. Тук паролата НИКОГА не
     е сменяна — проверителят в базата се отваря с ключа на сесията — тоест
     ключът е верният, а единственият криптиран ред е просто повреден:
     'unreadable', сесията остава отключена и стойността може да се въведе
     наново веднага. */
  const { db, ipcMain, ret, pii, key } = fx.pdpSetup('inv-v2420-unreadable-');
  const foreign = pii.deriveKey('чужд-ключ-999', pii.generateSalt(2));
  db.prepare('INSERT INTO readers (name, egn) VALUES (?, ?)')
    .run('Повреден', pii.encryptField('7501010001', foreign));
  const rows = ret.maskReaderRows(db.prepare('SELECT * FROM readers').all());
  assert.equal(rows[0].pii_masked_reason, 'unreadable');
  assert.equal(ipcMain.invoke('pdp:status').data.unlocked, true, 'сесията НЕ се обявява за негодна');
  // Същото и по единичния път (картон, сканиране на карта) — v2.4.21, находка №2.
  const one = ret.maskReaderRow(db.prepare('SELECT * FROM readers').get());
  assert.equal(one.pii_masked_reason, 'unreadable');
  // И въвеждането наново е възможно: новата стойност се криптира с добрия ключ.
  const out = { egn: '7501010001', id_card_no: null };
  ret.preparePiiForWrite(out, { egn: rows[0].egn, id_card_no: null });
  assert.equal(pii.decryptField(out.egn, key), '7501010001');
});

test('картонът при „stale“ казва, че данните са непокътнати, а при „unreadable“ — че се въвеждат наново веднага', async () => {
  const card = async (reason, fields) => {
    // Плейсхолдър стои САМО в маскираните полета — иначе фикстурата сама поставя
    // надписа на документа (преглед на поправките, v2.4.23).
    const dom = fx.buildDom({
      'readers.get': {
        id: 7, name: 'Читател', card_no: 'K-11',
        egn: fields.includes('egn') ? 'Защитени данни (ключът не съвпада)' : '7501010001',
        id_card_no: fields.includes('id_card_no') ? 'Защитени данни (ключът не съвпада)' : 'АА1234567',
        pii_masked: true, pii_masked_fields: fields, pii_masked_reason: reason, registered_at: '2026-01-01'
      },
      'loans.byReader': []
    });
    await fx.settle();
    await dom.window.printReaderCard(7);
    await fx.settle();
    return fx.printed(dom.window);
  };
  const stale = await card('stale', ['egn']);
  assert.match(stale, /сменена от друго работно място/);
  assert.match(stale, /Записаната стойност е непокътната/, 'stale вече има точно едно значение и обещанието е вярно');
  assert.match(stale, /отключете защитата/);
  assert.ok(!/наново само ако|въвеждайте|въведен[аи] наново|отключването откаже/.test(stale), 'при stale няма какво да се въвежда наново и няма условно указание');
  const unread = await card('unreadable', ['egn', 'id_card_no']);
  assert.match(unread, /записаните стойности не се разчитат/, 'множествено число за две полета');
  assert.match(unread, /Стойностите трябва да бъдат въведени наново/, 'и съгласувано в цялото изречение');
  assert.match(unread, /защитата е отключена и полетата се редактират/, 'указанието е изпълнимо');
  const unread1 = await card('unreadable', ['egn']);
  assert.match(unread1, /Стойността трябва да бъде въведена наново/, 'единствено число за едно поле');
  assert.match(unread1, /Лична карта: № АА1234567/, 'немаскираното поле се печата');
  for (const t of [stale, unread, unread1]) assert.ok(!/Защитени данни/.test(t), 'вътрешният надпис не отива на подписван документ');
  assert.match(unread, /самият запис е повреден, не паролата/);
});
