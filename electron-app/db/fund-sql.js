/* ---- ЗАКРЪГЛЯНЕ ДО ЕВРОЦЕНТ — ЕДНО ЗА ЦЯЛАТА ПРОГРАМА (v2.4.67) -----------
   Дотук на шест места стоеше Math.round(x * 100) / 100. Грешката е класическа:
   1,005 в двоичен вид е 1,00499999999999989…, умножено по 100 дава
   100,49999999999999 и Math.round връща 100 — тоест 1,005 € ставаше 1,00 €
   вместо 1,01 €, а 1,015 € — 1,01 € вместо 1,02 €. Сумата се записва така в
   сметката, в квитанцията и в отчета.
   ПОПРАВКАТА: изместването на десетичната запетая става в ТЕКСТ („1.005e2“), не
   с умножение — низът се разчита точно като 100,5 и Math.round дава 101.
   Половинката се закръгля НАГОРЕ ПО АБСОЛЮТНА СТОЙНОСТ и за отрицателни числа
   (плащанията в сметката са отрицателни): −1,005 → −1,01, не −1,00.
   Нечислово → 0, както в досегашните копия. */
function toCents(x) {
  const n = Number(x);
  if (!Number.isFinite(n) || n === 0) return 0;
  /* Над 10^15 числото с плаваща запетая вече няма точност до цент — връща се
     както е (такава сума в библиотека не съществува, но функцията не бива да я
     изкривява). */
  if (Math.abs(n) >= 1e15) return n;
  /* Изместването с 2 знака чете и експонентата, защото String() на много малко
     или много голямо число вече е в експоненциален вид („1e-15“, „1e+21“) и
     простото долепване на „e2“ дава NaN. Обратното е деление на 100: то е точно
     (делението в IEEE 754 се закръгля коректно — 101 / 100 === 1.01). */
  const [mant, exp] = String(Math.abs(n)).split('e');
  const r = Math.round(Number(mant + 'e' + (Number(exp || 0) + 2))) / 100;
  if (r === 0) return 0;               // никога „-0“ — то се печата като „-0.00“
  return n < 0 ? -r : r;
}

