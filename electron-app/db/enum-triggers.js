/* „DROP ... IF EXISTS“ ПРЕДИ „CREATE“, А НЕ „CREATE ... IF NOT EXISTS“ (v2.4.56).
   =====================================================================
   КАКВО СТАВАШЕ ДОТУК. Тригерите се създаваха с CREATE TRIGGER IF NOT EXISTS.
   Върху ЧИСТА база това е без значение — тригер няма и се създава по списъка
   отгоре. Върху база, която вече работи, обаче IF NOT EXISTS значи буквално
   „намериш ли тригер с това име, не пипай нищо“ — и вътре в него остава СТАРИЯТ
   списък стойности, какъвто е бил в деня на миграцията, която го е създала.
   Тригерите се прилагат от миграция 5 и (втори път) от миграция 9 в main.js, а
   всяка издадена инсталация отдавна е на по-висока версия от тях. Тоест всяка
   нова стойност, добавена в списъка по-горе, стигаше САМО до нови инсталации.

   ЗАЩО Е ГРЕШНО ЗА БИБЛИОТЕКАРЯ. Точно този кръг добавя три нови стойности,
   които са ежедневни: статус „изгубен“, вид събитие „изгубен“ и вид начисление
   „обезщетение за изгубен документ“. Върху съществуваща база — тоест върху
   всяка реална библиотека — първото натискане на „Документът е изгубен“ щеше да
   се блъсне в стария тригер и да върне „Непозната стойност за books.status.“:
   съобщение, което не казва нищо на човека пред гишето, за поправка, която
   програмата уж носи. Обновяването щеше да изглежда като счупване.

   ЗАЩО ПОПРАВКАТА Е ТОЧНО ТАКАВА. Тригерът няма собствени данни — целият му
   смисъл е в текста му. Затова пресъздаването му е безобидно и превръща
   applyEnumTriggers() в това, което всички я мислят за: „приведи тригерите в
   базата към списъка в този файл“, независимо какво е заварено. DROP и CREATE
   за една и съща колона стоят ЕДИН ДО ДРУГ (а не всички DROP-ове най-отгоре), за
   да е възможно най-къс прозорецът, в който колоната стои непазена; изричен
   BEGIN/COMMIT тук НЕ може да се сложи, защото runMigrations() в main.js вече
   изпълнява миграциите в транзакция и вложената щеше да гръмне.
   Заради същата причина (миграциите 5 и 9 са отдавна минали) handlers/loans.js
   извиква applyEnumTriggers() сам, преди да запише изгубен документ — виж
   ensureLostSchema() там. */
function buildSql() {
  let sql = '';
  for (const { table, col, values, notNull } of ENUM_COLUMNS) {
    const list = values.map(v => `'${v}'`).join(',');
    const guard = notNull ? `NEW.${col} NOT IN (${list})` : `NEW.${col} IS NOT NULL AND NEW.${col} NOT IN (${list})`;
    sql += `DROP TRIGGER IF EXISTS trg_${table}_${col}_ins;\n`;
    sql += `CREATE TRIGGER trg_${table}_${col}_ins BEFORE INSERT ON ${table}
      WHEN ${guard} BEGIN SELECT RAISE(ABORT, 'Непозната стойност за ${table}.${col}.'); END;\n`;
    sql += `DROP TRIGGER IF EXISTS trg_${table}_${col}_upd;\n`;
    sql += `CREATE TRIGGER trg_${table}_${col}_upd BEFORE UPDATE OF ${col} ON ${table}
      WHEN ${guard} BEGIN SELECT RAISE(ABORT, 'Непозната стойност за ${table}.${col}.'); END;\n`;
  }
  return sql;
}

function applyEnumTriggers(db) {
  db.exec(buildSql());
}

